#!/usr/bin/env python3
"""Generate the per-blank demo scripts of note 08 section 7 (writes flow-demo-*.txt next to this file).

Each script restores a snapshot, freezes the machine, optionally presses a key, then logs one group of peeks per video blank
(`step` runs exactly one blank; after the first `dense` blanks one group per `stride` blanks).  Run from the repository root:

    flock /tmp/ref.lock build/vamiga-ref/ref --rom disks/kick12.rom --adf extracted/interceptor-autoboot.adf \\
        --script tools/vamiga-ref/scripts/flow-demo-start.txt --log extracted/captures/logs/flow-demo-start.txt
"""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
HEAD = "seglist extracted/interceptor.bin extracted/interceptor.map.json\nfreeze\n"
# blank counter, state pointer, mode byte, replay mode, gate, pause, countdown, fade level/target, view, camera, key pointer, step counter, leave request, location, aircraft
FIELDS = [("bl", "4A82C", 2), ("st", "1A6BC", 4), ("mode", "4A95E", 1), ("m903", "4A903", 1), ("gate", "4A84D", 1), ("pause", "4A866", 1),
          ("cd", "4AB8E", 2), ("lvl", "4A958", 1), ("tgt", "4A959", 1), ("view", "4A83D", 1), ("cam", "4A966", 1), ("kp", "54E5C", 4),
          ("n", "4A992", 2), ("esc", "4A8E2", 1), ("loc", "4A900", 1), ("ac", "4A901", 1), ("txt", "4A802", 2), ("sel", "4A83F", 1),
          ("c965", "4A965", 1), ("rec", "4A848", 1)]


def group(i, extra=()):
    return "".join("peek F:%s %d b%d_%s\n" % (a, n, i, lab) for lab, a, n in list(FIELDS) + list(extra))


def write(name, comment, snap, key_at, key, n, dense=150, stride=5, extra=(), pre=""):
    s = "# generated by gen-flow-demo.py: %s\nrestore %s\n%s%s" % (comment, snap, HEAD, pre)
    i = 0
    while i < n:
        s += group(i, extra)
        if key and i == key_at:
            s += "key %s\n" % key
        k = 1 if i < dense else stride
        s += ("step %d\n" % k) if k > 1 else "step\n"
        i += k
    open(os.path.join(HERE, "flow-demo-%s.txt" % name), "w").write(s)


write("start", "menu item 1 (demo): key 1 pressed at blank 3, per blank until the demo has run a while", "extracted/captures/flow-menu.vasnap", 3, "1", 700)
write("esc", "ESC during the demo (demo snapshot): key pressed at blank 3", "extracted/captures/demo.vasnap", 3, "ESC", 520)
