#!/usr/bin/env python3
"""Generate flow-egg-sweep-N.txt: every raw key 0x00-0x67 (except ESC and the shift keys) pressed once in free flight (airborne.vasnap),
with the variable block 0x4A700-0x4AE92 and the first 256 bytes of the player record dumped before and after (note 08 section 11).
Needs ref with raw key names (key 0x66).  Usage: gen-flow-egg.py  (writes the 8 scripts next to this file)."""
import os
here = os.path.dirname(os.path.abspath(__file__))
keys = [k for k in range(0x00, 0x68) if k not in (0x45, 0x60, 0x61)]
groups = [keys[i:i + 12] for i in range(0, len(keys), 12)]
for gi, g in enumerate(groups):
    L = ["# generated by gen-flow-egg.py: key census, group %d (free flight)" % gi,
         "restore extracted/captures/airborne.vasnap",
         "seglist extracted/interceptor.bin extracted/interceptor.map.json",
         "wait 1"]
    for tag in ("c0", "c1"):                      # two control samples without a key (noise)
        L += ["freeze", "peek F:4A700 1938 %s_v" % tag, "peek F:4B23C 256 %s_r" % tag, "thaw", "wait 0.7"]
    for k in g:
        L += ["freeze", "peek F:4A700 1938 k%02X_a" % k, "peek F:4B23C 256 k%02X_ar" % k, "thaw",
              "key 0x%02X 0.15" % k, "wait 0.7",
              "freeze", "peek F:4A700 1938 k%02X_b" % k, "peek F:4B23C 256 k%02X_br" % k, "thaw"]
    open(os.path.join(here, "flow-egg-sweep-%d.txt" % gi), "w").write("\n".join(L) + "\n")
print(len(groups), "scripts")
