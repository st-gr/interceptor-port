def script(name, snap, header, events, blanks, extra_peeks=(), tail=(), colors=True):
    """events: {blank: [command lines]} executed before the peeks of that blank."""
    L = ["# " + header, "# generated by gen-flow-s1.py; run: build/vamiga-ref/ref --rom disks/kick12.rom --adf extracted/interceptor-autoboot.adf --script %s --log extracted/captures/logs/%s.txt" % ("tools/vamiga-ref/scripts/" + name + ".txt", name)]
    L.append("restore " + snap)
    L.append("seglist " + IMG)
    L.append("freeze")
    for b in range(blanks):
        for c in events.get(b, []):
            L.append(c)
        for (lab, a, n) in list(TRACK) + list(extra_peeks):
            L.append("peek F:%s %d b%d_%s" % (a, n, b, lab))
        if colors:
            L.append("colors b%d_col" % b)
        L.append("step")
    for c in tail:
        L.append(c)
    open(os.path.join(HERE, name + ".txt"), "w").write("\n".join(L) + "\n")


def block(tag, snap, events, blanks, extra_peeks=(), colors=True, track=None):
    """One scenario: restore, freeze, per-blank tracking; labels are t<tag>b<blank>_<var>."""
    L = ["restore " + snap, "seglist " + IMG, "freeze"]
    for b in range(blanks):
        for c in events.get(b, []):
            L.append(c)
        for (lab, a, n) in list(track or TRACK) + list(extra_peeks):
            L.append("peek F:%s %d t%db%d_%s" % (a, n, tag, b, lab))
        if colors:
            L.append("colors t%db%d_col" % (tag, b))
        L.append("step")
    return L


def multi(name, header, blocks, out=None):
    L = ["# " + header, "# generated by gen-flow-s1.py; run: build/vamiga-ref/ref --rom disks/kick12.rom --adf extracted/interceptor-autoboot.adf --script tools/vamiga-ref/scripts/%s.txt --log extracted/captures/logs/%s.txt" % (name, name)]
    for b in blocks:
        L += b
    open(out or os.path.join(HERE, name + ".txt"), "w").write("\n".join(L) + "\n")


