    # SHIFT-ESC in flight
    write("shiftesc-flight", hdr("SHIFT-ESC in free flight (airborne snapshot)", "extracted/captures/airborne.vasnap"),
          "key LSHIFT 0.6\nkey ESC 0.12\n", 330, colors_every=1, dense=150, stride=4, light=True, frames=(3, 8, 12, 20, 40, 100), frame_name="sesc")
