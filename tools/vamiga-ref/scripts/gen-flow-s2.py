#!/usr/bin/env python3
"""Generate the per-blank flow scripts of note 08 sections 5.10-5.14 and 6 (fork S2).

    python3 tools/vamiga-ref/scripts/gen-flow-s2.py            # writes flow-s2-*.txt next to this file

Every script restores a snapshot, freezes the machine, optionally stages (poke) and presses a key, then logs one group of
peeks per video blank (`step` runs exactly one blank), so the logs are independent of wall-clock jitter.  Run from the
repository root with the log written to a file (a log of this kind is a few hundred KB):

    flock /tmp/ref.lock build/vamiga-ref/ref --rom disks/kick12.rom --adf extracted/interceptor.adf \\
        --script tools/vamiga-ref/scripts/flow-s2-esc-flight.txt --log extracted/captures/logs/flow-s2-esc-flight.txt
"""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
HEAD = "seglist extracted/interceptor.bin extracted/interceptor.map.json\nfreeze\n"
# (label, address, length): the state pointer, the gate, the pause byte, the countdown, the fade level and target, the text list and the engine bytes
FIELDS = [("blank", "4A82C", 2), ("st", "1A6BC", 4), ("mode", "4A95E", 1), ("loc", "4A900", 1), ("ac", "4A901", 1),
          ("esc", "4A8E2", 1), ("e3", "4A8E3", 1), ("o850", "4A850", 1), ("gate", "4A84D", 1), ("pause", "4A866", 1),
          ("cd", "4AB8E", 2), ("lvl", "4A958", 1), ("tgt", "4A959", 1), ("txt", "4A802", 4), ("idx", "4A87E", 1),
          ("act", "4A87B", 1), ("g898", "4A898", 1), ("hold", "4A7FC", 2), ("n", "4A992", 2), ("allow", "4A94F", 1),
          ("cam", "4A966", 1), ("c965", "4A965", 1), ("sec", "4A964", 1), ("tries", "4A950", 1), ("demo", "4A903", 1),
          ("view", "4A83D", 1), ("sel", "4A83F", 1), ("a849", "4A849", 1), ("wait", "4A8E4", 1)]


LIGHT = [("blank", "4A82C", 2), ("st", "1A6BC", 4), ("mode", "4A95E", 1), ("gate", "4A84D", 1), ("cd", "4AB8E", 2), ("lvl", "4A958", 1),
         ("tgt", "4A959", 1), ("txt", "4A802", 4), ("act", "4A87B", 1), ("g898", "4A898", 1), ("cam", "4A966", 1), ("c965", "4A965", 1),
         ("sec", "4A964", 1), ("pause", "4A866", 1), ("n", "4A992", 2), ("f95b", "4A95B", 1), ("f95c", "4A95C", 1)]


def group(i, colors=False, frame=None, extra=(), light=False):
    s = ""
    for lab, a, n in list(LIGHT if light else FIELDS) + list(extra):
        s += "peek F:%s %d i%d_%s\n" % (a, n, i, lab)
    if colors:
        s += "colors i%d_col\n" % i
    if frame:
        s += "frame extracted/captures/flow/%s-%d.ppm\n" % (frame, i)
    return s


def run(name, comment, pre, n, colors_every=0, frames=(), frame_name=None, extra=(), after_first=""):
    s = "# generated by gen-flow-s2.py: " + comment + "\n" + pre + HEAD
    return name, s, n, colors_every, frames, frame_name, extra, after_first


def write(name, header, stage, n, colors_every=1, frames=(), frame_name=None, extra=(), tail="", dense=150, stride=4, light=False):
    """n blanks in all: one group per blank for the first `dense`, then one per `stride` blanks (the label number i is the blank)."""
    s = header + stage
    i = 0
    while i < n:
        s += group(i, colors=(colors_every and i % colors_every == 0), frame=(frame_name if i in frames else None), extra=extra, light=light)
        k = 1 if i < dense - 1 else stride
        s += "step %d\n" % k if k > 1 else "step\n"
        i += k
    s += tail
    open(os.path.join(HERE, "flow-s2-%s.txt" % name), "w").write(s)


def hdr(comment, snap):
    return "# generated by gen-flow-s2.py: %s\nrestore %s\n%s" % (comment, snap, HEAD)


if __name__ == "__main__":
    # ESC in free flight (cockpit, airborne snapshot, free flight mode 1): k counts blanks from the key press
    write("esc-flight", hdr("ESC (raw 0x45) in free flight, from the airborne snapshot; k = blanks after the key", "extracted/captures/airborne.vasnap"),
          "key ESC 0.12\n", 420, colors_every=1, frames=(5, 36, 40, 45, 60, 100, 140, 200, 260, 320), frame_name="escf", dense=140)
    write("esc-flight-dense", hdr("ESC in free flight, light field set, every blank for 440 blanks", "extracted/captures/airborne.vasnap"),
          "key ESC 0.12\n", 380, colors_every=1, dense=10000, light=True)
    # ESC in a pause
    write("esc-pause", hdr("P, then ESC in the pause (airborne snapshot)", "extracted/captures/airborne.vasnap"),
          "key P 0.12\nstep 20\nkey ESC 0.12\n", 420, colors_every=1, frames=(5, 24, 27, 40, 60, 100, 140, 200, 260, 320), frame_name="escp", dense=140)
    # P: pause enter and leave
    write("pause", hdr("P pressed in free flight (airborne snapshot), then P again after 60 blanks", "extracted/captures/airborne.vasnap"),
          "key P 0.12\n", 70, colors_every=1, frames=(10, 30, 60), frame_name="pause", dense=10000, light=True,
          tail="key P 0.12\n" + "".join(group(100 + i, colors=True, light=True) + "step\n" for i in range(60)))
    # game over: the fifth crash (allowance poked to 1), from the dive snapshot; the hold ends about 98 blanks after the crash bit
    write("gameover", hdr("game over: allowance poked to 1, crash staged by the dive snapshot (see crash-setup-dive.txt); k from V:4A951 = 3", "extracted/captures/dive-precrash.vasnap"),
          "poke F:4A94F 1 1\nstepuntil F:4B23C 2 and 0x0200 400\nstepuntil F:4A951 1 eq 3 200\n", 200, colors_every=1, frames=(8, 30, 60, 85, 100, 105, 112, 140, 170), frame_name="go", dense=10000, light=True)
    # mission start: aircraft selection (F/A-18) to the first flight pass
    write("mission-start", hdr("free flight: key 1 on the aircraft selection (aircraft-select.vasnap) to flight; k from the key", "extracted/captures/aircraft-select.vasnap"),
          "key 1 0.12\n", 520, colors_every=1, frames=(2, 20, 40, 80, 120, 160, 200, 240, 300), frame_name="ms", dense=250, stride=4, light=True,
          extra=[("a901", "4A901", 1), ("a900", "4A900", 1), ("allow", "4A94F", 1), ("o850", "4A850", 1), ("h7fc", "4A7FC", 2)])
    # the same, long: the camera approach (mode 6) and what ends it; one group per 6 blanks
    write("mission-start-long", hdr("free flight: key 1 on the aircraft selection, 1800 blanks at one group per 6 blanks", "extracted/captures/aircraft-select.vasnap"),
          "key 1 0.12\n", 1800, colors_every=0, frames=(), dense=1, stride=6, light=True,
          extra=[("view", "4A83D", 1), ("c90f", "4A90F", 1), ("a86d", "4A86D", 1), ("a86c", "4A86C", 1)])
    # mission end, staged: the mission script's success request (V:4A850 = 0xFF, V:4A978 = 0, V:4A8E2 = 3, V:4A8E4 = 4, V:4A965 = 1, as the code at 0x28AC6-0x28AE4
    # stores it) on the free-flight snapshot with the mode byte poked to MODE.  STAGED: no mission is running, so the outcome texts are those of the mode's list.
    for mode, code, tag in ((3, 0xFF, "m3-success"), (4, 0xFE, "m4-failure"), (9, 0xFF, "m9-success")):
        write("end-" + tag, hdr("mission end staged (%s): mode byte poked to %d, V:4A850 = 0x%02X, V:4A8E2 = 3, V:4A8E4 = 4, V:4A965 = 1; k from the first step after the pokes" % (tag, mode, code), "extracted/captures/airborne.vasnap"),
              "poke F:4A95E 1 %d\npoke F:4A850 1 %d\npoke F:4A978 2 0\npoke F:4A8E2 1 3\npoke F:4A8E4 1 4\npoke F:4A965 1 1\n" % (mode, code), 330,
              colors_every=1, frames=(5, 20, 40, 80, 120, 160, 200, 260, 320), frame_name="end-" + tag, dense=10000, light=True,
              extra=[("o850", "4A850", 1), ("e2", "4A8E2", 1), ("e3", "4A8E3", 1), ("a866", "4A866", 1)])
    # KP-ENTER during the camera approach (mode 6) of the free-flight start
    write("mission-start-skip", hdr("free flight: key 1, 250 blanks of approach, then KP-ENTER; k from the KP-ENTER", "extracted/captures/aircraft-select.vasnap"),
          "key 1 0.12\nstep 250\nkey KPENTER 0.12\n", 330, colors_every=1, frames=(4, 40, 100, 160), frame_name="skip", dense=10000, light=True,
          extra=[("view", "4A83D", 1), ("c90f", "4A90F", 1), ("a86d", "4A86D", 1), ("a86c", "4A86C", 1), ("k85b", "4A85B", 1)])
    # ESC twice: the second ESC arrives 60 blanks after the first, during the echo screen of the restart
    write("esc-twice", hdr("ESC in free flight, a second ESC 60 blanks later (Review Focus 5: ESC during the restart screens)", "extracted/captures/airborne.vasnap"),
          "key ESC 0.12\nstep 60\nkey ESC 0.12\n", 330, colors_every=0, dense=10000, light=True)
    # ESC during the game-over text
    write("gameover-esc", hdr("game over, then ESC 40 blanks into the text (k from V:4A951 = 3 plus 40)", "extracted/captures/dive-precrash.vasnap"),
          "poke F:4A94F 1 1\nstepuntil F:4B23C 2 and 0x0200 400\nstepuntil F:4A951 1 eq 3 200\nstep 40\nkey ESC 0.12\n", 330, colors_every=0, dense=10000, light=True)
    # location keys above 4 (the table walk of 0x1EB96): which values reach V:4A900
    for key in ("5", "7"):
        write("loc-key" + key, hdr("location selection: key %s (V:4A900 candidates above 3); k from the key" % key, "extracted/captures/location-select.vasnap"),
              "key %s 0.12\n" % key, 90, colors_every=0, dense=10000, light=True,
              extra=[("loc", "4A900", 1), ("ac", "4A901", 1), ("a86d", "4A86D", 1), ("a849", "4A849", 1)])
    # bail-out landing end, staged: the request 2 that the entity code stores at 0x27C58 (V:4A8E2 = 2, V:4A8E4 = 4) on the free-flight snapshot
    write("end-bailout", hdr("bail-out end staged: V:4A8E2 = 2, V:4A8E4 = 4 (as 0x27C58 stores them); k from the first step after the pokes", "extracted/captures/airborne.vasnap"),
          "poke F:4A8E2 1 2\npoke F:4A8E4 1 4\n", 330, colors_every=1, frames=(5, 30, 60, 100, 150, 200, 260), frame_name="end-bailout", dense=10000, light=True,
          extra=[("o850", "4A850", 1), ("e2", "4A8E2", 1), ("e3", "4A8E3", 1), ("a866", "4A866", 1)])
