#!/usr/bin/env python3
"""Generates the flow-training-*.txt scripts (docs/re/08-game-flow.md, section 8) next to this file.

    python3 gen-flow-training.py            # writes all of them
    python3 gen-flow-training.py part2      # one family: part1, part1-esc, part1-return, part1-splits-low, part2, part2-keys, part2-esc, part2-crash

Every script samples the same variables per step (the instructor record 0x4BA3C and the player record 0x4B23C, the lesson number
V:4A851, the trigger state V:4A852, the cursor V:54E42, the message code V:4AB98, the text ids V:4A802, the state pointer) with `peek` and
advances with `step`, so a log is read with tools/vamiga-ref/logparse.py.  The scripts need the snapshots made by
flow-training-menu.txt and flow-training-prompts.txt and the git-ignored disks/countercodes.txt (the answers of the two frozen challenges
194A and 3CCE, peeked by flow-training-prompts.txt; they differ if the snapshots are made again).
The state pointer 0xC0AA26 (flight state 0x12EFE) and 0xC09... values are RAM addresses of the first load (`seglist` prints them);
`stepuntil` on them is valid for the snapshots made from the same boot only.
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
PEEKS = [("blank", "4A82C", 2), ("st", "1A6BC", 4), ("mode", "4A95E", 1), ("les", "4A851", 1), ("flag", "4A852", 1), ("cur", "54E42", 2),
         ("g84b", "4A84B", 1), ("view", "4A83D", 1), ("dir", "4A96A", 1), ("g84d", "4A84D", 1), ("g898", "4A898", 1), ("msg", "4AB98", 2),
         ("txt", "4A802", 8), ("n", "4A992", 2), ("p866", "4A866", 1), ("ins", "4BA3C", 0x70), ("ply", "4B23C", 0x70), ("b8e", "4AB8E", 2),
         ("v903", "4A903", 1)]
END = [("g850", "4A850", 1), ("v8e2", "4A8E2", 1), ("v978", "4A978", 2), ("allow", "4A94F", 1), ("v8e4", "4A8E4", 1)]   # the end-check variables
SEG = "seglist extracted/interceptor.bin extracted/interceptor.map.json"
FLIGHT = "0xC0AA26"        # RAM address of the flight state 0x12EFE in the snapshots (hunk 0 at C07B28)


class G:
    def __init__(self, title):
        self.l = ["# " + title, "# Generated by gen-flow-training.py; see docs/re/08-game-flow.md section 8."]
        self.i = 0

    def c(self, x): self.l.append(x)

    def sample(self, n, step, extra=()):
        for _ in range(n):
            for lab, a, ln in list(PEEKS) + list(extra):
                self.c("peek F:%s %d s%d_%s" % (a, ln, self.i, lab))
            self.c("step %d" % step)
            self.i += 1

    def mark(self, t): self.c("log MARK %s at sample %d" % (t, self.i))

    def key(self, k, hold=None):
        self.c("thaw"); self.c("key %s%s" % (k, " %s" % hold if hold else "")); self.c("freeze"); self.c("step 3")

    def write(self, name):
        open(os.path.join(HERE, "flow-training-%s.txt" % name), "w").write("\n".join(self.l) + "\n")


def part1_head(g):
    g.c("restore extracted/captures/training-code-3.vasnap"); g.c(SEG)
    g.c("code @disks/countercodes.txt 194A"); g.c("freeze")


def part2_head(g):
    g.c("restore extracted/captures/training-code-4.vasnap"); g.c(SEG)
    g.c("code @disks/countercodes.txt 3CCE"); g.c("freeze")
    g.c("stepuntil F:1A6BC 4 eq %s 6000" % FLIGHT); g.c("step 100")
    g.key("F8")           # 80 percent thrust: the lead starts when the player's indicated speed is not zero


def part2_prompt_head(g):
    g.c("restore extracted/captures/training-part2-prompt.vasnap"); g.c(SEG); g.c("freeze"); g.c("step 5")


def main(which):
    if which in (None, "part1"):               # the whole cycle of part 1 (lessons 1 to 7 and the wrap)
        g = G("Part 1 (mode 2): sampled every 50 blanks from the first lesson through one cycle and the start of the next")
        part1_head(g); g.c("stepuntil F:4A851 1 gt 0 4000"); g.c("step 1"); g.sample(165, 50); g.write("part1")
    if which in (None, "part1-esc"):           # ESC in part 1 starts part 2
        g = G("ESC in part 1 at lesson 2: the next sampled screens (text ids 0x68, 0x0A) and the 0x7D flight")
        part1_head(g); g.c("stepuntil F:4A851 1 gt 1 6000"); g.c("step 3"); g.key("ESC"); g.sample(50, 25)
        g.write("part1-esc")
    if which in (None, "part1-return"):        # RETURN skips a lesson; the keypad view; the camera reset at the next advance
        g = G("RETURN in part 1 at lesson 2 (skip), the keypad view KP5 and the camera reset of the next advance")
        part1_head(g); g.c("stepuntil F:4A851 1 eq 2 6000"); g.c("step 30"); g.sample(4, 10)
        g.mark("RETURN (skip)"); g.key("RETURN"); g.sample(20, 10)
        g.mark("KP5 (view from above)"); g.key("KP5"); g.sample(6, 10); g.c("frame extracted/captures/training-part1-kp5.ppm")
        g.sample(70, 25); g.write("part1-return")
    if which in (None, "part1-splits-low"):    # the split-S limit (entry 53)
        g = G("Part 1: the instructor below the split-S limit when lesson 4 would start (staged with poke)")
        part1_head(g); g.c("stepuntil F:4A851 1 eq 3 6000"); g.c("stepuntil F:4BA41 1 eq 0x0A 4000")
        g.c("log STAGING: the instructor altitude (record 4 +0x18) is set to 0x0F0000, below the split-S limit 0x100000")
        g.c("poke F:4BA54 4 0x0F0000"); g.sample(70, 10)
        g.c("frame extracted/captures/training-part1-splits-low.ppm"); g.write("part1-splits-low")
    if which in (None, "part2"):               # take-off, prompt, RETURN, RETURN (skip), trigger
        g = G("Part 2 (mode 0x7D): F8, the take-off (the climb is cut short with poke), the prompt, two RETURNs and the trigger")
        part2_head(g); g.c("peek F:4A83C 12 switches"); g.c("stepuntil F:4BA41 1 eq 0x25 6000")
        g.c("log STAGING: the instructor altitude (record 4 +0x18) is set to 0x23F800 so that the climb ends in a few steps")
        g.c("poke F:4BA54 4 0x23F800"); g.sample(60, 10); g.mark("after END"); g.sample(60, 10); g.mark("prompt expected"); g.sample(40, 10)
        g.mark("RETURN 1"); g.key("RETURN"); g.sample(25, 10)
        g.mark("RETURN 2"); g.key("RETURN"); g.sample(25, 10)
        g.mark("SPACE trigger"); g.key("SPACE"); g.sample(60, 10); g.write("part2")
        g = G("Part 2: the same start, stopped at the first prompt; writes the snapshot the part2-* scripts restore")
        part2_head(g); g.c("stepuntil F:4BA41 1 eq 0x25 6000")
        g.c("log STAGING: the instructor altitude (record 4 +0x18) is set to 0x23F800 so that the climb ends in a few steps")
        g.c("poke F:4BA54 4 0x23F800"); g.c("stepuntil F:4A852 1 eq 0xFF 4000")
        g.c("peek F:4A990 2 hudoff_w"); g.c("peek F:4A9D0 4 hudoff_l"); g.c("peek F:4A94F 1 allowance"); g.c("peek F:4AB98 2 msg")
        g.c("frame extracted/captures/training-part2-prompt.ppm"); g.c("snapshot extracted/captures/training-part2-prompt.vasnap")
        g.write("part2-prompt")
    if which in (None, "part2-keys"):          # S, RETURN, RETURN (skip), trigger, RETURN mid-lesson
        g = G("Part 2 from the first prompt: S twice, RETURN, RETURN (skip), the trigger, RETURN and SPACE mid-lesson (not ready, no effect)")
        part2_prompt_head(g); g.sample(4, 10)
        g.mark("S"); g.key("S"); g.sample(4, 10); g.mark("S again"); g.key("S"); g.sample(3, 10)
        g.mark("RETURN 1"); g.key("RETURN"); g.sample(8, 10); g.c("frame extracted/captures/training-part2-reposition.ppm")
        g.mark("RETURN 2 (skip)"); g.key("RETURN"); g.sample(8, 10)
        g.mark("SPACE trigger"); g.key("SPACE"); g.sample(12, 10)
        g.mark("RETURN mid-lesson"); g.key("RETURN"); g.sample(12, 10)
        g.c("frame extracted/captures/training-part2-notready.ppm")
        g.mark("SPACE mid-lesson (no effect)"); g.key("SPACE"); g.sample(12, 10); g.write("part2-keys")
    if which in (None, "part2-esc"):
        g = G("ESC in part 2 from the first prompt: where the flow goes")
        part2_prompt_head(g); g.sample(4, 10); g.mark("ESC"); g.key("ESC"); g.sample(100, 25)
        g.c("frame extracted/captures/training-part2-esc-end.ppm"); g.write("part2-esc")
    if which in (None, "part2-shiftesc"):
        g = G("SHIFT-ESC in part 2 from the first prompt: where the flow goes (the main menu is expected)")
        part2_prompt_head(g); g.sample(4, 10); g.mark("SHIFT-ESC")
        g.c("thaw"); g.c("keydown LSHIFT"); g.c("key ESC"); g.c("keyup LSHIFT"); g.c("freeze"); g.c("step 3"); g.sample(100, 25)
        g.c("frame extracted/captures/training-part2-shiftesc-end.ppm"); g.write("part2-shiftesc")
    if which in (None, "part1-shiftesc"):
        g = G("SHIFT-ESC in part 1 at lesson 2 (the main menu is expected)")
        part1_head(g); g.c("stepuntil F:4A851 1 gt 1 6000"); g.c("step 3"); g.mark("SHIFT-ESC")
        g.c("thaw"); g.c("keydown LSHIFT"); g.c("key ESC"); g.c("keyup LSHIFT"); g.c("freeze"); g.c("step 3"); g.sample(100, 25)
        g.c("frame extracted/captures/training-part1-shiftesc-end.ppm"); g.write("part1-shiftesc")
    if which in (None, "part1-keys"):          # the keys that part 1 ignores (the flight controls and the digits)
        g = G("Part 1: UP held (a flight control), the digit 5 (a throttle preset) and F5: the player record must not change")
        part1_head(g); g.c("stepuntil F:4A851 1 eq 2 6000"); g.c("step 30")
        ex = [("p928", "4A928", 1), ("p830", "4A830", 2)]
        g.sample(3, 10, ex); g.mark("UP 2 s"); g.c("thaw"); g.c("key UP 2"); g.c("freeze"); g.c("step 3"); g.sample(6, 10, ex)
        g.mark("digit 5"); g.key("5"); g.sample(6, 10, ex); g.mark("F5"); g.key("F5"); g.sample(6, 10, ex)
        g.mark("KP4 (view)"); g.key("KP4"); g.sample(6, 10, ex); g.write("part1-keys")
    if which in (None, "part2-collide"):       # the instructor lost: the end check of mode 0x7D (staged)
        g = G("Part 2: the instructor's W0 bit 0x0040 is cleared with poke (a mid-air collision gives the same state; flying the player through the instructor did not collide: offset +9 units)")
        part2_prompt_head(g); g.sample(3, 10, END)
        g.c("log STAGING: the instructor's W0 low byte (record 4 +0x01) is set to 0x88 (bit 0x40 clear: the instructor is gone)")
        g.c("poke F:4BA3D 1 0x88"); g.sample(120, 10, END)
        g.c("frame extracted/captures/training-part2-collide-end.ppm"); g.write("part2-collide")
    if which in (None, "part2-crash"):         # the first crash of part 2
        g = G("Part 2: RETURN into formation, then UP (stick forward, nose down) held until the crash (allowance 1)")
        part2_prompt_head(g); g.mark("RETURN"); g.key("RETURN"); g.sample(4, 10)
        g.c("log STAGING: the player altitude (record 0 +0x18) is set to 0x40000 (about 960 feet); holding UP for 9 s in a first trial made a loop, not a dive")
        g.c("poke F:4B254 4 0x40000")
        g.mark("dive"); g.c("thaw"); g.c("key UP 2"); g.c("freeze"); g.c("step 2"); g.sample(150, 10)
        g.c("frame extracted/captures/training-part2-crash-end.ppm"); g.write("part2-crash")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else None)
