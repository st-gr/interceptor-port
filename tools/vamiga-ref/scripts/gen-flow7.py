#!/usr/bin/env python3
"""Generate the game-flow captures of milestone 7, Task 2 (flow7-*.txt next to this file).

    python3 tools/vamiga-ref/scripts/gen-flow7.py [family ...]

Run from a checkout that has extracted/, disks/ and build/vamiga-ref/ (the main one, or a worktree with links to them), one script at a time:
    flock /tmp/ref.lock timeout 900 build/vamiga-ref/ref --rom disks/kick12.rom --adf extracted/interceptor-autoboot.adf \\
        --script tools/vamiga-ref/scripts/flow7-keys7890.txt --log extracted/captures/logs/flow7-keys7890.txt
Peeks and steps only; the staging pokes are named in each script.  The state pointer values are the RAM addresses of the first load
(seglist: hunk 0 at C07B28): 0xC0A880 is the approach state 0x12D58, 0xC0A8E0 the countdown state 0x12DB8.
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
SEG = "seglist extracted/interceptor.bin extracted/interceptor.map.json\n"
APPR = "0xC0A880"   # the approach state 0x12D58
DB8 = "0xC0A8E0"    # the state 0x12DB8


def write(name, comment, body):
    open(os.path.join(HERE, "flow7-%s.txt" % name), "w").write("# generated by gen-flow7.py: %s\n%s" % (comment, body))


def pk(fields, tag):
    return "".join("peek F:%s %d %s_%s\n" % (a, n, tag, lab) for lab, a, n in fields)


# the whole mover and HUD state of one approach pass
APF = [("n", "4A992", 2), ("st", "1A6BC", 4), ("cam", "4ACF6", 12), ("mode", "4A966", 1), ("stage", "4A86E", 1), ("row", "4AA3C", 2),
       ("step", "4AA3E", 2), ("view", "4A83D", 1), ("map", "4A865", 1), ("hud", "4A859", 1), ("loc", "4A900", 1), ("tgt", "4AD0E", 12)]


def keys7890():
    s = ""
    for key, idx in (("7", 6), ("8", 7), ("9", 8), ("0", 9)):
        s += "log RUN location key %s (V:4A900 = %d)\nrestore extracted/captures/location-select.vasnap\n%sfreeze\n" % (key, idx, SEG)
        s += "key %s 0.12\nstepuntil F:4A849 1 eq 1 2500\nstep 90\n" % key
        s += pk([("loc", "4A900", 1), ("pos", "4B23C", 0x30)], "k%s_air" % key)
        s += "key 1 0.12\nstepuntil F:1A6BC 4 eq %s 1500\n" % APPR
        s += pk(APF + [("pos", "4B23C", 0x30)], "k%s_in" % key)
        for j in range(1, 6):
            s += "step 20\n" + pk(APF, "k%s_s%d" % (key, j))
        s += "stepuntil F:1A6BC 4 eq %s 4000\n" % DB8
        s += pk(APF + [("pos", "4B23C", 0x30)], "k%s_out" % key)
    write("keys7890", "the location keys 7, 8, 9 and 0 (V:4A900 = 6..9): the approach state's step counter at the entry and the exit, and the mover every 20 blanks", s)


def approach_pass(kind, key, n0, npass):
    """The approach state 0x12D58 pass by pass: from the aircraft key (free flight, airfield) or the location key (carrier) to the state 0x12DB8,
    one group of peeks in the first video frame of every value of the step counter V:4A992 (a pass is about 10 blanks)."""
    s = "log RUN %s: location key %s\nrestore extracted/captures/location-select.vasnap\n%sfreeze\nkey %s 0.12\n" % (kind, key, SEG, key)
    if key != "4":
        s += "stepuntil F:4A849 1 eq 1 2500\nstep 90\nkey 1 0.12\n"
    s += "stepuntil F:1A6BC 4 eq %s 1500\n" % APPR
    s += pk(APF, "p%03d" % 0)
    for j in range(1, npass + 1):
        s += "stepuntil F:4A992 2 ne %d 80\n" % (n0 + j - 1)
        s += pk(APF, "p%03d" % j)
    s += "stepuntil F:1A6BC 4 eq %s 200\n" % DB8
    s += pk(APF, "pend")
    for j in range(4):
        s += "step 2\n" + pk(APF, "q%d" % j)
    write("approach-" + kind, "the approach state 0x12D58 of the %s start pass by pass (the first video frame of each step-counter value): mover state, HUD step and window row" % kind, s)


def training(mode, snap, chal):
    s = "log RUN training mode %s from the countercode answer: the HUD step and window row, the view, the camera and the state every 8 blanks\nrestore extracted/captures/%s.vasnap\n%s" % (mode, snap, SEG)
    s += "code @disks/countercodes.txt %s\nfreeze\n" % chal
    fields = APF + [("blank", "4A82C", 2), ("gate", "4A84D", 1), ("pmode", "4A95E", 1)]
    for i in range(0, 170):
        s += pk(fields, "t%03d" % i) + "step 8\n"
    write("training-%s" % mode, "the HUD step V:4AA3E, the window row V:4AA3C, the view and the camera from the countercode answer of training mode %s through its camera approach and into the flight" % mode, s)


