def rec(i): return 0x4B23C + 0x200 * i


def shoot(name, snap, tgt, comment, n=160, stride=2, extra_pokes=(), ply=0x80000, tgty=0x80000):
    """C8 and C4: the player's own missile at a staged target: the target record is poked ahead of the player's nose (+z, 0x7A000 units, just above the deck; 1,950 du), the lock V:4AA78 is poked to its offset, SPACE fires; the
    target record, the player's W0 and W2, the end code, the pause byte, the request, the counts and the projectile pool are sampled every `stride` blanks."""
    s = "log RUN %s\nrestore %s\n%sfreeze\n" % (comment, snap, SEG)
    s += "poke F:%X 4 0x%X\n" % (rec(0) + 0x18, ply)   # the player is lifted clear of the carrier's hull (a missile launched at deck height ends in the hull test of the ship record 14)
    s += "poke F:%X 4 0x11982C00\npoke F:%X 4 0x%X\npoke F:%X 4 0x105FA000\n" % (rec(tgt) + 0x14, rec(tgt) + 0x18, tgty, rec(tgt) + 0x1C)
    s += "poke F:4B29F 1 0x2D\npoke F:4B29B 1 0x44\n"   # the weapon selector E+0x63 (high nibble 2: the missile, the low nibble kept) and the stock E+0x5F
    for a in extra_pokes: s += a + "\n"
    s += "poke F:4AA78 2 0x%X\nstep 2\n" % (0x200 * tgt)
    f = [("blank", "4A82C", 2), ("st", "1A6BC", 4), ("tgt", "%X" % rec(tgt), 128), ("pl", "%X" % rec(0), 64), ("code", "4A850", 1), ("p866", "4A866", 1), ("req", "4A8E2", 1), ("cnt", "4A961", 3),
         ("n", "4A992", 2), ("lock", "4AA78", 2), ("pool", "4AD2A", 128), ("wpn", "4B29B", 6), ("w1", "%X" % rec(1), 64), ("w2", "%X" % rec(2), 64), ("w3", "%X" % rec(3), 64)]
    for i in range(n):
        if i == 1: s += "key SPACE 0.4\n"
        s += pk(f, "x%03d" % i) + "step %d\n" % stride
    write(name, comment, s)


