def brief(m):
    """The briefing of mission mode m: from the menu key to the state 0x126F6, then the blank counter, the engine byte and the state every blank for 600 blanks (the typing ends with the engine byte 1)."""
    s = "log RUN mode %d (%s): the briefing's typing, every blank\nrestore extracted/captures/mb/menu.vasnap\n%sfreeze\n" % (m, KEY[m], SEG)
    for off, v in POKES.get(m, []): s += "poke R:%X 1 %d\n" % (RECPTR + off, v)
    s += "key %s 0.12\npeek F:4A82C 2 key_blank\nstepuntil F:1A6BC 4 eq %s 1500\n" % (KEY[m], S126F6)
    for i in range(600):
        s += pk(TYPE, "t%03d" % i) + "step\n"
    write("brief-m%d" % m, "mode %d: the typing of the intro and briefing records (state 0x126F6) every blank: the blank counter, the engine byte (1 = the list is typed) and the state" % m, s)


