def qual_digits():
    """The qualification's answer typed digit by digit (4 blanks apart), RETURN, then every blank to the briefing. The script carries the answer, so it is written to extracted/scratch (ignored by the
    repository), never next to this file; the committed qual-answer script uses the `code` command instead."""
    ans = [l.split()[1] for l in open(os.path.join(HERE, "..", "..", "..", "disks", "countercodes.txt")) if l.split()[:1] == ["F7BD"]][0]
    ev = {}
    k = 3
    for ch in ans:
        ev[k] = "key %s 0.04" % ch
        k += 4
    ev[k + 2] = "key RETURN 0.06"
    s = "log RUN qualification: the answer typed digit by digit, RETURN at sample %d\nrestore extracted/captures/qual-prompt.vasnap\n%sfreeze\n" % (k + 2, SEG)
    for i in range(0, 300):
        s += pk(STF + [("p965", "4A965", 1), ("e3", "4A8E3", 1), ("txt", "4A802", 8)], "a%03d" % i)
        if i in ev: s += ev[i] + "\n"
        s += "step\n"
    out = os.path.join(HERE, "..", "..", "..", "extracted", "scratch", "flow7-qual-answer-digits.txt")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    open(out, "w").write("# generated by gen-flow7.py (scratch, carries the answer)\n" + s)


