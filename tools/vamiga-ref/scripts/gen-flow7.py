def latch(name, comment, head, keyat, n, first_key, extra):
    """A key every 6 blanks (about one step) from first_key; per blank the pass counter V:4A879, the key ring's write index V:4A8AF, the latch V:4A85B; the ring's count V:4A8B1 is poked to 0 after every sample
    (staging: a full ring (10) refuses further keys and would end the census)."""
    s = head
    for i in range(n):
        s += pk([("blank", "4A82C", 2), ("pass", "4A879", 1), ("widx", "4A8AF", 1), ("cnt", "4A8B1", 1), ("latch", "4A85B", 1), ("st", "1A6BC", 4), ("gate", "4A84D", 1),
                 ("g898", "4A898", 1), ("mode", "4A966", 1)] + extra, "b%03d" % i)
        s += "poke F:4A8B1 1 0\n"
        if i in keyat: s += keyat[i] + "\n"
        s += "step\n"
    write(name, comment, s)


