#!/usr/bin/env python3
"""Generate the briefing/approach/scan captures of Task 2 B2 (note 08 12.14 C13, 13.4 C1 and C12, 12.5 C10, 13.1 C11).

    python3 tools/vamiga-ref/scripts/gen-followup-b2.py

Writes followup-airfield-start.txt, followup-airfield-start-2.txt, followup-brief-camera.txt, followup-brief-camera-s7.txt,
followup-radar-scan.txt, followup-brief-skip.txt, followup-visibility.txt. Run each with --rw --log under flock /tmp/ref.lock.
Prerequisites: the snapshots of gen-mission-brief.py / mission-brief-menu.txt (extracted/captures/mb/), location-select.vasnap,
disks/countercodes.txt. State addresses are the run-time addresses of the state routines (seg 0 at RAM C07B28 for flat 0x10000).
"""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
HEAD = "seglist extracted/interceptor.bin extracted/interceptor.map.json\n"
RECPTR = 0xC54498


def st(off):
    return "0x%X" % (0xC07B28 + off - 0x10000)


def pk(i, items):
    return "".join("peek F:%s %d i%d_%s\n" % (a, n, i, lab) for lab, a, n in items)


FLOW = [("n", "4A992", 2), ("st", "1A6BC", 4), ("cam", "4ACF6", 12), ("mode", "4A966", 1)]
STG = [("a86d", "4A86D", 1), ("a86e", "4A86E", 1), ("a967", "4A967", 1)]


def write(name, s):
    open(os.path.join(HERE, name), "w").write(s)


def airfield(name, keys):
    s = "# generated by gen-followup-b2.py: free-flight start from the location screen, one run per location key %s: the aircraft prompt, key 1, the approach 0x12D58 sampled every 4 blanks (step counter, state, camera, camera mode); C13\n" % keys
    for key in keys:
        s += "log run location key %d\nrestore extracted/captures/location-select.vasnap\n" % key + HEAD + "freeze\nkey %d 0.12\n" % key
        if key != 4:
            s += "stepuntil F:4A849 1 eq 1 2500\nstep 90\n" + pk(0, FLOW) + "key 1 0.12\n"
        s += "stepuntil F:1A6BC 4 eq %s 1500\n" % st(0x12D58)
        for i in range(330):
            s += pk(i, FLOW) + "step 4\n"
        s += pk(999, FLOW)
    write(name, s)


def brief_camera():
    s = "# generated by gen-followup-b2.py: F2 from the countercode prompt snapshot: the answer typed, then every 2 blanks the step counter, state, camera position, camera mode, V:4A86D, V:4A86E, V:4A967 and the target to the first pass of 0x12AC0 and beyond; C1\n"
    s += "restore extracted/captures/mb/m4-prompt.vasnap\n" + HEAD + "code @disks/countercodes.txt 3284\nfreeze\n"
    for i in range(260):
        s += pk(i, FLOW + STG + [("tgt", "4AD0E", 12), ("trail", "4AD06", 4)]) + "step 2\n"
    write("followup-brief-camera.txt", s)
    s = "# generated by gen-followup-b2.py: F2 from the menu: the approach target state 0x12744 and stage 7, every blank; C1 (stage 7 part)\n"
    s += "restore extracted/captures/mb/menu.vasnap\n" + HEAD + "freeze\nkey F2 0.12\nstepuntil F:1A6BC 4 eq %s 3000\n" % st(0x12744)
    for i in range(90):
        s += pk(i, FLOW + STG + [("tgt", "4AD0E", 12), ("rec", "4AA72", 2), ("trail", "4AD06", 4)]) + "step 1\n"
    write("followup-brief-camera-s7.txt", s)


def radar():
    s = "# generated by gen-followup-b2.py: F1 first flight pass (mb/m3-flight.vasnap), the MiG staged beside the player with the lock set as mission-m3-ok.txt; every 2 blanks the step counter and the walk counter V:4A927 for 700 blanks; C10\n"
    s += "restore extracted/captures/mb/m3-flight.vasnap\n" + HEAD + "freeze\npoke F:4AA78 2 0x1400\npoke F:4C650 4 0x10945920\npoke F:4C658 4 0x10E404F0\npoke F:4C654 4 0x00080000\n"
    for i in range(380):
        s += pk(i, [("n", "4A992", 2), ("c927", "4A927", 1), ("view", "4A996", 1), ("lock", "4AA78", 2), ("r8ef", "4A8EF", 1), ("r8f0", "4A8F0", 1)]) + "step 2\n"
    write("followup-radar-scan.txt", s)


def skip():
    s = "# generated by gen-followup-b2.py: F2 from the countercode prompt snapshot: the answer typed, 100 blanks into the orders text KP-ENTER, then every 2 blanks the state, step counter, camera mode and the start bytes; C11\n"
    s += "restore extracted/captures/mb/m4-prompt.vasnap\n" + HEAD + "code @disks/countercodes.txt 3284\nfreeze\nstep 100\n"
    items = FLOW + STG + [("loc", "4A900", 2), ("ac", "4A901", 1), ("k", "4A965", 1), ("txt", "4A802", 8), ("g898", "4A898", 1), ("gate", "4A84D", 1)]
    s += pk(-1, items) + "key KPENTER 0.12\n"
    for i in range(300):
        s += pk(i, items) + "step 4\n"
    write("followup-brief-skip.txt", s)


def visibility():
    s = "# generated by gen-followup-b2.py: stage 7 of the briefing camera with the placement sub-list 2 and 3 (completion byte of the mode poked): F2 (mode 4, byte +0x16) and F4 (mode 6, byte +0x18, unlock +0x17); C12\n"
    runs = [("F2", 4, 0x16, 2), ("F2", 4, 0x16, 3), ("F4", 6, 0x18, 2), ("F4", 6, 0x18, 3)]
    for key, mode, off, val in runs:
        s += "log run %s sub-list %d\nrestore extracted/captures/mb/menu.vasnap\n" % (key, val) + HEAD + "freeze\n"
        if mode == 6:
            s += "poke R:%X 1 1\n" % (RECPTR + 0x17)
        s += "poke R:%X 1 %d\npeek R:%X 78 rec_before\nkey %s 0.12\n" % (RECPTR + off, val, RECPTR, key)
        s += "stepuntil F:1A6BC 4 eq %s 3000\n" % st(0x12744)
        for i in range(60):
            s += pk(i, FLOW + STG + [("tgt", "4AD0E", 12), ("rec", "4AA72", 2), ("sub", "4A7F2", 4), ("cnt", "4A961", 3)]) + "step 1\n"
    write("followup-visibility.txt", s)


def approach_state():
    s = "# generated by gen-followup-b2.py: the state of the camera mover at the start of the free-flight approach 0x12D58 (airfield 1 with the aircraft key, and the carrier): target, trail, stage, player position and matrix, then every 4 blanks the same; C13 (rig comparison)\n"
    items = [("n", "4A992", 2), ("cam", "4ACF6", 12), ("a86e", "4A86E", 1), ("tgt", "4AD0E", 12), ("trail", "4AD02", 12)]
    for key in (1, 4):
        s += "log run location key %d\nrestore extracted/captures/location-select.vasnap\n" % key + HEAD + "freeze\nkey %d 0.12\n" % key
        if key != 4:
            s += "stepuntil F:4A849 1 eq 1 2500\nstep 90\nkey 1 0.12\n"
        s += "stepuntil F:1A6BC 4 eq %s 1500\n" % st(0x12D58)
        s += "peek F:4B23C 256 player\npeek F:4A6E8 2000 vars\n"
        for i in range(330):
            s += pk(i, items) + ("step 1\n" if i < 24 else "step 4\n")
    write("followup-approach-state.txt", s)


approach_state()
airfield("followup-airfield-start.txt", [1, 2])
airfield("followup-airfield-start-2.txt", [3, 4])
brief_camera(); radar(); skip(); visibility()
