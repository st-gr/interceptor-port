#!/usr/bin/env python3
"""Generate the per-blank follow-up capture scripts of milestone 6, Task 2 (writes followup-*.txt next to this file).

A group of peeks per video blank (`step` is exactly one blank); keys are pressed after a given group.  Run from the repository root:
    flock /tmp/ref.lock timeout 900 build/vamiga-ref/ref --rom disks/kick12.rom --adf extracted/interceptor-autoboot.adf \\
        --script tools/vamiga-ref/scripts/followup-pause-gameover.txt --log extracted/captures/logs/followup-pause-gameover.txt
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
HEAD = "seglist extracted/interceptor.bin extracted/interceptor.map.json\nfreeze\n"
BASE = [("bl", "4A82C", 2), ("st", "1A6BC", 4), ("n", "4A992", 2), ("gate", "4A84D", 1), ("pause", "4A866", 1), ("cd", "4AB8E", 2),
        ("g898", "4A898", 1), ("txt", "4A802", 2), ("allow", "4A94F", 1), ("v984", "4A984", 2), ("req", "4A910", 1), ("c951", "4A951", 1)]


def group(p, i, fields):
    return "".join("peek F:%s %d %s%d_%s\n" % (a, n, p, i, lab) for lab, a, n in fields)


def run(fields, n, keys, p="b", colors=False, pre=""):
    """keys: {index: [key commands]}; a key command is pressed after the group of that index."""
    s = pre
    for i in range(n):
        s += group(p, i, fields)
        if colors: s += "colors %s%d_col\n" % (p, i)
        for k in keys.get(i, []): s += k + "\n"
        s += "step\n"
    return s


def write(name, comment, body):
    open(os.path.join(HERE, name), "w").write("# generated by gen-followup.py: %s\n%s" % (comment, body))


def pause_gameover():
    s = ""
    for tag, k1, k2, n in (("A", 1, 150, 210), ("B", 20, 100, 170), ("C", 105, 160, 210)):
        s += "log RUN_%s\nrestore extracted/captures/dive-precrash.vasnap\n%sposition_%s_placeholder\n" % (tag, HEAD, tag)
        s = s.replace("position_%s_placeholder\n" % tag,
                      "poke F:4A94F 1 1\nstepuntil F:4B23C 2 and 0x0200 400\nstepuntil F:4A951 1 eq 0 200\nlog K0_%s\n" % tag)
        s += run(BASE, n, {k1: ["key P 0.12"], k2: ["key P 0.12"]}, p=tag.lower())
    write("followup-pause-gameover.txt", "note 05 17.17 rule 7: P pressed during the game-over count (A: blank 1 and 150, B: blank 20 and 100, C: blank 105 and 160; index 0 is the first blank with the crash bit; needs crash-setup-dive.txt first", s)


ST = {"12E4E": "C0A976", "12DB8": "C0A8E0", "12D58": "C0A880", "11B9C": "C096C4"}   # state routine -> the pointer value in RAM (flat + 0xBF7B28)


def demo_esc():
    """ESC during the demo's fade-in (state 0x11B9C, 15/18/21 blanks after it first runs), three runs, the colour registers per blank."""
    f = [("bl", "4A82C", 2), ("st", "1A6BC", 4), ("lvl", "4A958", 1), ("tgt", "4A959", 1), ("gate", "4A84D", 1), ("pause", "4A866", 1),
         ("cd", "4AB8E", 2), ("n", "4A992", 2), ("esc", "4A8E2", 1), ("mode", "4A95E", 1), ("m903", "4A903", 1)]
    s = ""
    for tag, off in (("a", 15), ("b", 18), ("c", 21)):
        s += "log RUN_%s_ESC_AFTER_%d\nrestore extracted/captures/flow-menu.vasnap\n%skey 1\nstepuntil F:1A6BC 4 eq 0x%s 3000\nstep %d\nkey ESC\n" % (tag.upper(), off, HEAD, ST["11B9C"], off)
        s += run(f, 75, {}, p=tag, colors=True)
    write("followup-demo-esc.txt", "note 08 7.7, 5.11: ESC at 15, 18 and 21 blanks into the demo's fade-in (state 0x11B9C), the colour registers and the fade bytes per blank; needs flow-menu.vasnap", s)


def callsign_ring(sp=2, name="followup-callsign-ring.txt"):
    """11 keys typed on the credits screen and in the first-tour welcome, then the callsign entry opens; run with --rw and the zero-record ADF."""
    f = [("bl", "4A82C", 2), ("st", "1A6BC", 4), ("g898", "4A898", 1), ("ring", "4A899", 10), ("rwc", "4A8AF", 3), ("typed", "4A8A3", 12),
         ("inp", "4A8AD", 2), ("filt", "4A88D", 1), ("k85b", "4A85B", 1), ("txt", "4A802", 2)]
    s = "log RUN\nrestore extracted/captures/credits-zero.vasnap\n" + HEAD
    s += "peek R:C544B6 24 name0\nkey SPACE\n"
    keys = "ABCDEFGHIJK"
    nb = 0
    for i in range(190):
        s += group("r", i, f) + "peek R:C544B6 24 r%d_name\n" % i
        if i in (60, 120, 160, 189): s += "frame extracted/captures/logs/%s-%d.ppm\n" % (name[:-4], i)
        if 4 <= i < 4 + sp * len(keys) and (i - 4) % sp == 0: s += "key %s 0.08\n" % keys[(i - 4) // sp]
        s += "step 5\n"
    write(name, "note 08 5.8, 10.5: 11 letters typed %d groups of 5 blanks apart after the credits key (SPACE), before the callsign entry opens; the ring, the typed buffer and the record's callsign per 5 blanks; run with --rw --adf extracted/scratch/q/zero.adf; needs credits-zero.vasnap (flow-log-boot-zero.txt)" % sp, s)


def pause_screens():
    """P in the notice screen (free flight, take-off notice), in an outcome screen (staged mission end) and P in flight with the byte at 0 (passes with the byte at 0xFF)."""
    f = [("bl", "4A82C", 2), ("st", "1A6BC", 4), ("n", "4A992", 2), ("p879", "4A879", 1), ("gate", "4A84D", 1), ("pause", "4A866", 1), ("cd", "4AB8E", 2),
         ("g898", "4A898", 1), ("txt", "4A802", 2), ("lvl", "4A958", 1), ("tgt", "4A959", 1), ("cam", "4A966", 1), ("p968", "4A968", 1), ("rec", "4B23C", 32)]
    s = "log RUN_FLIGHT_P\nrestore extracted/captures/airborne.vasnap\n" + HEAD
    s += run(f, 40, {2: ["key P 0.12"], 25: ["key P 0.12"]}, p="f")
    s += "log RUN_OUTCOME_P\nrestore extracted/captures/airborne.vasnap\n" + HEAD
    for pk in ("poke F:4A95E 1 3", "poke F:4A850 1 255", "poke F:4A978 2 0", "poke F:4A8E2 1 3", "poke F:4A8E4 1 4", "poke F:4A965 1 1"): s += pk + "\n"
    s += run(f, 150, {70: ["key P 0.12"], 110: ["key P 0.12"]}, p="o")
    s += "log RUN_NOTICE_P\nrestore extracted/captures/aircraft-select.vasnap\n%skey 1\nstepuntil F:1A6BC 4 eq 0x%s 3000\nstep 10\nkey P 0.12\n" % (HEAD, ST["12E4E"])
    s += run(f, 120, {60: ["key P 0.12"]}, p="n")
    write("followup-pause-screens.txt", "note 08 6.4, 5.14, 12.11: P with the byte at 0 in flight (the passes at 0xFF), P in the staged outcome screen and in the take-off notice screen of free flight", s)


def pause_notice_keep():
    """P in the take-off notice screen and no second P: does the pause screen open when the flight state first runs?"""
    f = [("bl", "4A82C", 2), ("st", "1A6BC", 4), ("n", "4A992", 2), ("p879", "4A879", 1), ("gate", "4A84D", 1), ("pause", "4A866", 1), ("cd", "4AB8E", 2),
         ("g898", "4A898", 1), ("txt", "4A802", 2), ("lvl", "4A958", 1), ("tgt", "4A959", 1), ("p968", "4A968", 1)]
    s = "restore extracted/captures/aircraft-select.vasnap\n%skey 1\nstepuntil F:1A6BC 4 eq 0x%s 3000\nstep 10\nkey P 0.12\n" % (HEAD, ST["12E4E"])
    s += run(f, 150, {}, p="n")
    write("followup-pause-notice.txt", "note 08 6.4, 5.14: P in the take-off notice screen of free flight, no second P: the states after the notice with the pause byte 0xFF", s)


if __name__ == "__main__":
    for a in sys.argv[1:] or ["pause_gameover"]:
        globals()[a]()
    if "callsign_ring" in sys.argv[1:]: callsign_ring(3, "followup-callsign-ring-slow.txt")
