#!/usr/bin/env python3
"""Generate the briefing-chain captures of note 08 section 13 (menu F1..F6 = modes 3..8).

    python3 tools/vamiga-ref/scripts/gen-mission-brief.py [N1 STRIDE1]

Per mission: mission-brief-mM-a.txt (from the F key, frozen and stepped, to the countercode prompt; snapshot extracted/captures/mb/mM-prompt.vasnap) and
mission-brief-mM-b.txt (written by `gen-mission-brief.py M CHALLENGE`: from that snapshot, the answer typed, dense per blank to the first flight pass, then the records).
Prerequisite: mission-brief-menu.txt (writes extracted/captures/mb/menu.vasnap from credits-rw.vasnap).  Run with --rw and --log (flock /tmp/ref.lock).
The F5 and F6 runs poke the unlock bytes +0x18 (and +0x19) of the log record (the shipped log has them 0); this changes the completion counts of modes 6 and 7, not of the mission under test.
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
HEAD = "seglist extracted/interceptor.bin extracted/interceptor.map.json\n"
KEY = {3: "F1", 4: "F2", 5: "F3", 6: "F4", 7: "F5", 8: "F6"}
RECPTR = "C54498"   # the log record in the credits-rw snapshot (peek F:1D024 4 gives 00C54498)
POKES = {7: [(0x18, 1)], 8: [(0x18, 1), (0x19, 1)]}
LIGHT = [("blank", "4A82C", 2), ("st", "1A6BC", 4), ("gate", "4A84D", 1), ("cd", "4AB8E", 2), ("fade", "4A958", 2), ("txt", "4A802", 8),
         ("g898", "4A898", 1), ("g86e", "4A86E", 1), ("flags", "4A964", 4), ("e3", "4A8E3", 1), ("n", "4A992", 2), ("t72", "4AA72", 2), ("pause", "4A866", 1)]
CAM = [("cam", "4ACF6", 12), ("tgt", "4AD0E", 12)]
PLACE = [("var", "4ABD4", 2), ("b0", "4ABB0", 2), ("sub", "4A7F2", 4), ("cnt", "4A961", 3), ("prog", "4A95F", 2), ("a850", "4A850", 1), ("a966", "4A966", 1), ("a967", "4A967", 1)]


def group(i, extra=()):
    s = ""
    for lab, a, n in LIGHT + list(extra):
        s += "peek F:%s %d i%d_%s\n" % (a, n, i, lab)
    return s


def pokes(m):
    s = ""
    for off, v in POKES.get(m, []):
        s += "poke R:%X 1 %d\n" % (int(RECPTR, 16) + off, v)
    return s


def seg_a(m, n, stride):
    s = "# generated by gen-mission-brief.py: mode %d from the menu key %s to the countercode prompt, one group per %d blanks\n" % (m, KEY[m], stride)
    s += "restore extracted/captures/mb/menu.vasnap\n" + HEAD + "freeze\n" + pokes(m)
    s += "peek R:%s 78 rec_before\n" % RECPTR
    s += "key %s 0.12\n" % KEY[m]
    i = 0
    while i < n:
        s += group(i, CAM + PLACE)
        s += "step %d\n" % stride
        if i % (stride * 20) == 0:
            s += "frame extracted/captures/mb/m%d-a-%d.ppm\n" % (m, i)
        i += stride
    s += "peek F:440A8 48 chal\nframe extracted/captures/mb/m%d-prompt.ppm\nsnapshot extracted/captures/mb/m%d-prompt.vasnap\n" % (m, m)
    open(os.path.join(HERE, "mission-brief-m%d-a.txt" % m), "w").write(s)


RECS = [4, 6, 8, 10, 11, 12, 14, 15]
RFIELDS = [(0, 2), (2, 2), (6, 2), (0xC, 2), (0x14, 4), (0x1C, 4), (0x5D, 1), (0x62, 2), (0x38, 1), (0x3A, 1), (0x4C, 2)]


LIGHT_B = [("blank", "4A82C", 2), ("st", "1A6BC", 4), ("gate", "4A84D", 1), ("cd", "4AB8E", 2), ("fade", "4A958", 2), ("txt", "4A802", 8),
           ("g898", "4A898", 1), ("g86e", "4A86E", 1), ("flags", "4A964", 4), ("n", "4A992", 2), ("a849", "4A849", 1)]
FLIGHT_STATE = 0xBF7B28 + 0x12EFE      # RAM address of the flight state routine in the credits-rw boot (seg 0 ram C07B28)


def grp(i, extra=()):
    s = ""
    for lab, a, n in LIGHT_B + list(extra):
        s += "peek F:%s %d i%d_%s\n" % (a, n, i, lab)
    return s


def seg_b(m, chal):
    """After the countercode: the orders screen, the aircraft prompt (only F1, the airfield start, asks: the carrier-start modes go straight to the player start), key 1 (F1 only), the approach, the notice, the first flight pass."""
    s = "# generated by gen-mission-brief.py: mode %d from the countercode prompt (challenge %s): orders, aircraft prompt, key 1, approach to the first flight pass\n" % (m, chal)
    s += "restore extracted/captures/mb/m%d-prompt.vasnap\n" % m + HEAD
    s += "code @disks/countercodes.txt %s\nfreeze\n" % chal
    i = 0
    def log(i, stride, extra=()):
        return grp(i, extra) + ("step\n" if stride == 1 else "step %d\n" % stride)
    while i < 200:
        s += log(i, 1, CAM if i % 50 == 0 else []); i += 1
    s += "frame extracted/captures/mb/m%d-b-orders.ppm\n" % m
    while i < 1100:
        s += log(i, 8); i += 8
        if i % 200 == 0: s += "frame extracted/captures/mb/m%d-b-%d.ppm\n" % (m, i)
    s += "stepuntil F:4A849 1 eq 1 2500\nstep 90\n"
    s += grp(5000, CAM) + "frame extracted/captures/mb/m%d-b-aircraft.ppm\n" % m
    s += "key 1 0.12\n"
    j = 0
    while j < 1900:
        s += grp(6000 + j, CAM if j % 100 == 0 else [])
        k = 1 if j < 40 else 10
        s += "step\n" if k == 1 else "step %d\n" % k
        if j % 400 == 0: s += "frame extracted/captures/mb/m%d-c-%d.ppm\n" % (m, j)
        j += k
    s += "stepuntil F:1A6BC 4 eq 0x%X 3000\n" % FLIGHT_STATE
    s += grp(9999, CAM + PLACE)
    s += "frame extracted/captures/mb/m%d-flight.ppm\n" % m
    for r in RECS:
        for off, ln in RFIELDS:
            s += "peek F:%X %d rec%d_%02X\n" % (0x4B23C + 0x200 * r + off, ln, r, off)
    s += "peek F:1D024 4 recptr\npeek R:%s 78 rec_after\n" % RECPTR
    for q in range(1, 4):
        s += "step 4\n" + grp(9999 + q)
    open(os.path.join(HERE, "mission-brief-m%d-b.txt" % m), "w").write(s)


if __name__ == "__main__":
    if len(sys.argv) == 3 and len(sys.argv[2]) == 4:
        seg_b(int(sys.argv[1]), sys.argv[2])
    else:
        n = int(sys.argv[1]) if len(sys.argv) > 1 else 3600
        st = int(sys.argv[2]) if len(sys.argv) > 2 else 6
        for m in range(3, 9): seg_a(m, n, st)
