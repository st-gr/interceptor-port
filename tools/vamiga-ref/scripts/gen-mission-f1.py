#!/usr/bin/env python3
"""mission-m3-ok.txt: F1 (mode 3) success from the first flight passes (mission-m3-start.txt): the MiG (record 10) is moved next to the player and the target lock V:4AA78 is
set (staged), then the scope walk's counter V:4A927 is sampled until the script ends the mission, and the debrief; then the landing (staged position on the pad) for 0xFC.
Run with --rw under flock after mission-m3-start.txt."""
import sys
out = ["# generated by gen-mission-f1.py: F1 identification (staged: the MiG moved beside the player, the lock set)",
       "restore extracted/captures/mb/m3-flight.vasnap", "seglist extracted/interceptor.bin extracted/interceptor.map.json", "freeze",
       "poke F:4AA78 2 0x1400",
       # the player is at x 0x10545920, z 0x10A404F0 (cell 65,66): the MiG is put 1 cell east and 1 cell ahead, at a low height
       "poke F:4C650 4 0x10945920", "poke F:4C658 4 0x10E404F0", "poke F:4C654 4 0x00080000"]
S = [("st", "1A6BC", 4), ("txt", "4A802", 8), ("a850", "4A850", 32), ("e2", "4A8E2", 4), ("w978", "4A978", 2), ("wB8E", "4AB8E", 2), ("w992", "4A992", 2),
     ("w927", "4A927", 2), ("w93B", "4A93B", 2), ("w8EF", "4A8EF", 2), ("lock", "4AA78", 2), ("mig", "4C63C", 0x80), ("mig2", "4C23C", 0x80), ("pl", "4B23C", 0x80)]
def sample(tag):
    for n, a, l in S:
        out.append("peek F:%s %d %s_%s" % (a, l, tag, n))
    out.append("peek R:C54498 78 %s_log" % tag)
for i in range(120):
    out.append("step 4"); sample("s%d" % i)
out.append("frame extracted/captures/logs/mission-m3-ok.ppm")
out.append("snapshot extracted/captures/mb/m3-after.vasnap")
open(sys.argv[1] if len(sys.argv) > 1 else "mission-m3-ok.txt", "w").write("\n".join(out) + "\n")
