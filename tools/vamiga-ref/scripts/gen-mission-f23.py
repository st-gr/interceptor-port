#!/usr/bin/env python3
"""mission-m4-all.txt and mission-m5-all.txt: the F2 (mode 4) and F3 (mode 5) script paths from the first flight pass (mission-m4-start.txt, mission-m5-start.txt snapshots).
STAGED throughout: the records are changed by poke (the principal aircraft's active bit 0x1000 is cleared so the AI and the step do not rewrite what the script reads).
Branches (each from a fresh restore): F2: ok (Air Force One on the ground, slow, the fighters gone), fe (it is gone: failure with the parity of V:4A992 as it comes), fe_odd / fe_even
(V:4A992 poked), fd (gone with B20 bit 0x80), dead (code 4 poked: the script stays dead), pause (key P in the frozen passes), esc (ESC in them).
F3: ok (kills 2, timer -1), fail (a thief inactive and its x poked to cell 0x70), shadow (the player on the thief for 230 passes; the timer V:4A83A and the destinations).
Run with --rw under flock."""
import sys

def hdr(m, comment):
    return ["# generated by gen-mission-f23.py: " + comment, "restore extracted/captures/mb/m%d-flight.vasnap" % m, "seglist extracted/interceptor.bin extracted/interceptor.map.json", "freeze"]

S2 = [("st", "1A6BC", 4), ("txt", "4A802", 8), ("a850", "4A850", 32), ("e2", "4A8E2", 4), ("w978", "4A978", 2), ("wB8E", "4AB8E", 2), ("w992", "4A992", 2),
      ("a95e", "4A95E", 6), ("w83a", "4A83A", 2), ("a876", "4A876", 1), ("a96a", "4A96A", 1), ("a8eb", "4A8EB", 1), ("a83d", "4A83D", 1), ("w994", "4A994", 2),
      ("r4", "4BA3C", 0x70), ("r6", "4BE3C", 0x70), ("r8", "4C23C", 0x40)]
def sample(out, tag):
    for n, a, l in S2: out.append("peek F:%s %d %s_%s" % (a, l, tag, n))
    out.append("peek R:C54498 78 %s_log" % tag)

def steps(out, tag, n, k=2):
    for i in range(n):
        out.append("step %d" % k); sample(out, "%s%d" % (tag, i))

def f2():
    br = {}
    R4 = 0x4BA3C
    # ok: W0 of record 4 without the active bit, on the ground, slow; records 8 and 10 without the valid bit
    o = hdr(4, "F2 success (staged)") + ["poke F:%X 2 0x40D8" % R4, "poke F:%X 2 0x0080" % (R4 + 2), "poke F:%X 2 0" % (R4 + 0x6C), "poke F:%X 2 0x3091" % 0x4C23C]
    steps(o, "o", 160); br["ok"] = o
    # fe: record 4 invalid
    for name, par in (("fe", None), ("fe_odd", 0x1001), ("fe_even", 0x1000)):
        o = hdr(4, "F2 failure (staged): Air Force One gone, B20 bit 0x80 clear" + ("" if par is None else ", V:4A992 poked to %#x" % par)) + ["poke F:%X 2 0x4098" % R4]
        if par is not None: o.append("poke F:4A992 2 %#x" % par)
        steps(o, "o", 160); br[name] = o
    o = hdr(4, "F2 code 0xFD (staged): gone with B20 bit 0x80") + ["poke F:%X 2 0x4098" % R4, "poke F:%X 1 0xC0" % (R4 + 0x20)]
    steps(o, "o", 160); br["fd"] = o
    o = hdr(4, "F2 after a crash code (staged): V:4A850 = 4, then the aircraft gone; the script must stay dead; ESC after 40 samples") + ["poke F:4A850 1 4", "poke F:%X 2 0x4098" % R4]
    steps(o, "o", 40); o += ["key ESC 0.3"]; steps(o, "e", 120, 4); br["dead"] = o
    o = hdr(4, "F2 with P in the frozen passes (staged trigger)") + ["poke F:%X 2 0x4098" % R4]
    steps(o, "o", 3, 1); o += ["key P 0.12"]; steps(o, "p", 40, 1); o += ["key P 0.12"]; steps(o, "q", 100, 2); br["pause"] = o
    o = hdr(4, "F2 with ESC in the frozen passes (staged trigger)") + ["poke F:%X 2 0x4098" % R4]
    steps(o, "o", 3, 1); o += ["key ESC 0.3"]; steps(o, "p", 150, 4); br["esc"] = o
    return br

def f3():
    br = {}
    R4, R6 = 0x4BA3C, 0x4BE3C
    o = hdr(5, "F3 success (staged): kills 2, timer -1, thieves valid and neutral") + ["poke F:4A963 1 2", "poke F:4A83A 2 0xFFFF"]
    steps(o, "o", 160); br["ok"] = o
    o = hdr(5, "F3 failure (staged): the first thief made inactive and its cell x poked to 0x70") + ["poke F:%X 2 0x00D9" % R4, "poke F:%X 4 0x1C000000" % (R4 + 0x14)]
    steps(o, "o", 160); br["fail"] = o
    # shadow: record 4 inactive, the player moved onto the thief; one step per sample so that the near passes are seen before the player falls away
    pl = ["poke F:%X 2 0x01C8" % 0x4B23C, "poke F:4B250 4 0x1076C474", "poke F:4B258 4 0x12A00000", "poke F:4B254 4 0xAE3EC"]
    o = hdr(5, "F3 shadowing (staged): the thief inactive, the player on it; then the timer set to -1 and the player put back (the destinations are re-installed)") + ["poke F:%X 2 0x00D9" % R4] + pl
    steps(o, "w", 40, 1)
    o += ["poke F:4A83A 2 0xFFFF", "poke F:4BE68 2 0x7E"] + pl      # the second thief is sent on to the second waypoint (cell 126) first
    steps(o, "x", 10, 1)
    br["shadow"] = o
    return br

if __name__ == "__main__":
    for m, f in ((4, f2), (5, f3)):
        for name, lines in f().items():
            open("mission-m%d-%s.txt" % (m, name), "w").write("\n".join(lines) + "\n")
            print("mission-m%d-%s.txt" % (m, name), len(lines))
