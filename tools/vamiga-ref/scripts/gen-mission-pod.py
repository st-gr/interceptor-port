#!/usr/bin/env python3
"""mission-m6-ok.txt: F4 (mode 6) with the parachute released (SHIFT and F) and, right after it is created (before it lands), its x and z set to the pod's (staged), so that the
script's near case runs; samples of the end code, the request, the text, the parachute record and the log.  Prerequisite: extracted/captures/mission-m6-flight.vasnap
(written by mission-m6-out-a.txt).  Run with --rw under flock."""
import sys
out = ["# generated by gen-mission-pod.py: F4 near case (staged: the parachute record is moved onto the pod right after it is created)",
       "restore extracted/captures/mission-m6-flight.vasnap", "seglist extracted/interceptor.bin extracted/interceptor.map.json", "freeze",
       "keydown LSHIFT", "key F 0.12", "keyup LSHIFT"]
S = [("st", "1A6BC", 4), ("txt", "4A802", 8), ("a850", "4A850", 32), ("e2", "4A8E2", 4), ("w978", "4A978", 2), ("wB8E", "4AB8E", 2), ("w992", "4A992", 2),
     ("w97A", "4A97A", 2), ("par", "4B43C", 128), ("pod", "4C83C", 128), ("log", None, 78)]
def sample(tag):
    for n, a, l in S:
        out.append("peek R:C54498 78 %s_log" % tag if n == "log" else "peek F:%s %d %s_%s" % (a, l, tag, n))
out.append("stepuntil F:4A97A 2 ne 0 600")
sample("born")
# the pod's position longs (record 11 +0x14, +0x1C) read from the first flight pass of mission-m6-out-a.txt: x 0x12700000, z 0x11100000
out += ["poke F:4B450 4 0x12700000", "poke F:4B458 4 0x11100000"]   # right after the parachute record exists (before it lands)
sample("moved")
for i in range(40):
    out.append("step 4"); sample("b%d" % i)
out.append("stepuntil F:4A850 1 ne 0 2000")
for i in range(60):
    out.append("step 4"); sample("c%d" % i)
out.append("frame extracted/captures/logs/mission-m6-ok.ppm")
open(sys.argv[1] if len(sys.argv) > 1 else "mission-m6-ok.txt", "w").write("\n".join(out) + "\n")
