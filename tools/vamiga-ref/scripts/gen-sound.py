#!/usr/bin/env python3
"""Generate the sound capture scripts of note 10 (docs/re/10-sound.md, Verified by): sound-*.txt next to this file.

    python3 tools/vamiga-ref/scripts/gen-sound.py

Every script restores a snapshot (or boots), freezes the machine, switches `audtrace` and `wav` on, presses keys and runs the machine with `step` (one video
blank per step), so the logs are independent of wall-clock jitter; the register writes come from `audtrace`, the game's own state from `peek` groups.  Run each
one at a time under the emulator lock, from the repository root:

    flock /tmp/ref.lock timeout 900 build/vamiga-ref/ref --rom disks/kick12.rom --adf extracted/interceptor-autoboot.adf \\
        --script tools/vamiga-ref/scripts/sound-menu.txt --log extracted/captures/logs/sound-menu.txt

The recordings go to extracted/captures/audio/ (git-ignored).
"""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
SEG = "seglist extracted/interceptor.bin extracted/interceptor.map.json\n"
WAV = "extracted/captures/audio/%s.wav"


def head(snap, name, mode="frame", extra=""):
    """mode: frame (one line per video frame: fast), watch (every register write, DMACON included) or nodmacon (every audio register write)"""
    s = "# %s\n# generated by gen-sound.py (note 10); see that file for how to run it.\n" % name
    s += "restore extracted/captures/%s\n" % snap + SEG + "freeze\n" + extra
    s += "audtrace on%s\nwav %s start\n" % ({"frame": " frame", "watch": "", "nodmacon": " nodmacon"}[mode], WAV % name)
    return s


def tail(name):
    return "wav %s stop\naudtrace off\n" % (WAV % name)


# the sound state: master level, its target, the typing-sound byte, the blank counter
SND = ["peek F:54FBE 4 m", "peek F:4A720 4 t", "peek F:4A88F 1 f", "peek F:4A82C 2 bl"]
# the inputs of the per-pass sound routine (note 10 section 5): the globals 0x4A83C..0x4A96B in one group, the viewed record, the speed-scaled distance word
PASSIN = ["peek F:4A83C 304 g", "peek F:4B23C 128 r0", "peek F:4ABFA 2 d", "peek F:54FBE 4 m", "peek F:4A720 4 t", "peek F:4A88F 1 f", "peek F:4AC10 4 en", "peek F:4A82C 2 bl"]



def lab(peeks, tag):
    return [p + "_" + tag for p in peeks]


def stepseq(n, per, peeks, tag):
    out = []
    for i in range(0, n, per):
        out.append("step %d" % min(per, n - i))
        out += lab(peeks, "%s%d" % (tag, i))
    return out


def write(name, text):
    with open(os.path.join(HERE, name + ".txt"), "w") as f:
        f.write(text)


def main():
    # 1 the cold boot: the start-up phrase, audio.device, the CIA state (the filter bit); 400 s of wall clock under the trace
    s = "# sound-boot: cold boot of the autoboot disk with the audio register trace and the recording; 8,200 frames (164 s of emulated time) are stepped\n"
    s += "# (the game loads for about 150 s, plays its start-up sound, shows the credits).\n"
    s += "wait 1\nfreeze\naudtrace on frame\nwav %s start\nstep 8200\nwav %s stop\naudtrace off\n" % (WAV % "sound-boot", WAV % "sound-boot")
    s += "peek R:BFE001 1 ciaa_pra\npeek R:BFE201 1 ciaa_ddra\npeek R:BFD000 1 ciab_pra\n"
    write("sound-boot", s)

    # 2 the menu: the key at the credits (target 0x1F0000: the ramp), the log-disk prompt (typed clicks), RETURN, the menu build and its music
    L = [head("credits.vasnap", "sound-menu"), "\n".join(SND[:3]) + "\n", "key SPACE 0.06\n"]
    L.append("\n".join(stepseq(150, 1, SND, "r")) + "\n")
    L.append("\n".join(stepseq(300, 10, SND, "p")) + "\n")
    L.append("key RETURN 0.06\n")
    L.append("\n".join(stepseq(150, 1, SND, "m")) + "\n")
    L.append("\n".join(stepseq(2400, 50, SND, "t")) + "\n")
    L.append(tail("sound-menu"))
    write("sound-menu", "".join(L))

    # 3 the key clicks of a typed text screen: the credits key, the log-disk prompt typing
    L = [head("credits.vasnap", "sound-click", mode="watch"), "key SPACE 0.06\n", "\n".join(stepseq(90, 10, SND, "c")) + "\n", tail("sound-click")]
    write("sound-click", "".join(L))

    # 3b the echo line and the dispatch of a mode key in the menu (key 5: free flight): the menu music, the stop at the mode's start
    L = [head("flow-menu.vasnap", "sound-menu-mode"), "\n".join(SND + ["peek F:1A6BC 4 st"]) + "\n", "key 5 0.06\n", "\n".join(stepseq(900, 6, SND + ["peek F:1A6BC 4 st"], "k")) + "\n", tail("sound-menu-mode")]
    write("sound-menu-mode", "".join(L))

    # 4 the flight start of free flight (mode 1): the code is typed in real time, the trace starts at the aircraft key
    def flight_start(name, snap, code, mode_keys):
        s = "# %s: %s\n# the countercode is typed in real time (not traced), the trace starts at the aircraft key; needs the git-ignored disks/countercodes.txt.\n" % (name, snap)
        s += "restore extracted/captures/%s\n" % snap + SEG
        s += "code @disks/countercodes.txt %s\n" % code[0]
        for k in mode_keys[:-1]:
            s += k + "\n"
        s += "freeze\n" + "\n".join(SND + ["peek F:4A95E 1 mode"]) + "\n"
        s += "audtrace on frame\nwav %s start\n" % (WAV % name) + mode_keys[-1] + "\n"
        s += "\n".join(stepseq(1900, 20, PASSIN[:1] + PASSIN[3:], "f")) + "\n" + tail(name)
        return s
    write("sound-flight-start", flight_start("sound-flight-start", "code-prompt.vasnap", ("5D5A",), ["wait 6", "key 1", "wait 6", "key 1 0.12"]))
    write("sound-flight-start-m3", flight_start("sound-flight-start-m3", "mb/m3-prompt.vasnap", ("429C",), ["wait 16", "key 1 0.12"]))

    # 5 a throttle sweep and the afterburner (F1 twice: idle; F5; F10: afterburner; F3; the brake) in the air, the inputs sampled every 6 blanks
    L = [head("airborne.vasnap", "sound-throttle"), "\n".join(PASSIN) + "\n"]
    for i, (k, n) in enumerate((("F1", 240), ("F1", 240), ("F5", 300), ("F10", 300), ("F3", 300), ("F10", 200), ("F1", 200))):
        L.append("key %s 0.06\n" % k)
        L.append("\n".join(stepseq(n, 6, PASSIN, "%s%d_" % (k, i))) + "\n")
    L.append(tail("sound-throttle"))
    write("sound-throttle", "".join(L))

    # 5b the afterburner: military power (F10), then the throttle-up key held past the detent (the afterburner on: notice 0xFD), then the throttle-down key (off: 0xFC)
    L = [head("airborne.vasnap", "sound-afterburner"), "\n".join(PASSIN) + "\n", "key F10 0.06\n", "\n".join(stepseq(300, 6, PASSIN, "m")) + "\n",
         "keydown EQUALS\n", "\n".join(stepseq(120, 6, PASSIN, "ab")) + "\n", "keyup EQUALS\n", "\n".join(stepseq(240, 6, PASSIN, "hold")) + "\n",
         "keydown MINUS\n", "\n".join(stepseq(60, 6, PASSIN, "off")) + "\n", "keyup MINUS\n", "\n".join(stepseq(240, 6, PASSIN, "after")) + "\n", tail("sound-afterburner")]
    write("sound-afterburner", "".join(L))

    # 5c the CIA state and the enable longs at the credits (the filter bit; the sound bits the loaders set)
    write("sound-cia", "# sound-cia: the CIA port registers and the sound enable longs in the credits snapshot (note 10 1.5, 2.3)\nrestore extracted/captures/credits.vasnap\n" + SEG + "freeze\n"
          "peek R:BFE001 1 ciaa_pra\npeek R:BFE201 1 ciaa_ddra\npeek R:BFD000 1 ciab_pra\npeek R:BFD200 1 ciab_ddra\npeek F:4AC10 4 enable\npeek F:54FBE 4 master\npeek F:4A88F 1 flag\n")

    # 6 the gear (G), the hook (A), the brake (backslash), a take-off from the runway with the ground noise, the gear after it
    L = [head("cockpit-ground.vasnap", "sound-gear-touchdown"), "\n".join(PASSIN) + "\n", "key F10 0.06\n", "\n".join(stepseq(420, 6, PASSIN, "to")) + "\n",
         "keydown DOWN\n", "\n".join(stepseq(60, 6, PASSIN, "rot")) + "\n", "keyup DOWN\n", "\n".join(stepseq(300, 6, PASSIN, "cl")) + "\n",
         "key G 0.06\n", "\n".join(stepseq(120, 6, PASSIN, "gu")) + "\n", "key G 0.06\n", "\n".join(stepseq(120, 6, PASSIN, "gd")) + "\n", tail("sound-gear-touchdown")]
    write("sound-gear-touchdown", "".join(L))

    # 6b the gear key in the air (the gear sound: voice 2, 10 in the cockpit; the hook key A: a beep) and in the outside view (volume 5)
    L = [head("airborne.vasnap", "sound-gear"), "\n".join(PASSIN) + "\n", "key G 0.06\n", "\n".join(stepseq(240, 6, PASSIN, "g1_")) + "\n", "key G 0.06\n", "\n".join(stepseq(240, 6, PASSIN, "g2_")) + "\n",
         "key A 0.06\n", "\n".join(stepseq(60, 6, PASSIN, "a_")) + "\n", "key KPENTER 0.06\n", "\n".join(stepseq(60, 6, PASSIN, "x_")) + "\n", "key G 0.06\n", "\n".join(stepseq(240, 6, PASSIN, "g3_")) + "\n",
         "key G 0.06\n", "\n".join(stepseq(240, 6, PASSIN, "g4_")) + "\n", tail("sound-gear")]
    write("sound-gear", "".join(L))

    # 7 the crash: the dive snapshot, then the fall into the sea and the hold after the crash
    L = [head("dive-precrash.vasnap", "sound-crash"), "\n".join(PASSIN) + "\n", "\n".join(stepseq(600, 6, PASSIN, "k")) + "\n", tail("sound-crash")]
    write("sound-crash", "".join(L))

    # 8 the ejection: SHIFT-E in the cockpit, and the same in the outside view
    L = [head("airborne.vasnap", "sound-eject"), "\n".join(PASSIN) + "\n", "keydown LSHIFT\nkey E 0.12\nkeyup LSHIFT\n", "\n".join(stepseq(900, 6, PASSIN, "e")) + "\n", tail("sound-eject")]
    write("sound-eject", "".join(L))
    L = [head("airborne.vasnap", "sound-eject-ext"), "\n".join(PASSIN) + "\n", "key KPENTER 0.06\n", "\n".join(stepseq(60, 6, PASSIN, "v")) + "\n",
         "keydown LSHIFT\nkey E 0.12\nkeyup LSHIFT\n", "\n".join(stepseq(900, 6, PASSIN, "e")) + "\n", tail("sound-eject-ext")]
    write("sound-eject-ext", "".join(L))

    # 9 the weapons in free flight: the selection cycles with RETURN (0x0D, 0x3D, 0x2D, ...); SPACE is held for half a second at each (the gun, the AIM-9L, the AIM-120 and the
    # flare/chaff releases F and C are keys of their own)
    L = [head("airborne.vasnap", "sound-gun-launch"), "\n".join(PASSIN) + "\n"]
    for i in range(6):
        L.append("key RETURN 0.06\n" if i else "")
        L.append("\n".join(stepseq(24, 6, PASSIN, "w%d_" % i)) + "\n")
        L.append("keydown SPACE\n")
        L.append("\n".join(stepseq(36, 6, PASSIN, "f%d_" % i)) + "\n")
        L.append("keyup SPACE\n")
        L.append("\n".join(stepseq(90, 6, PASSIN, "a%d_" % i)) + "\n")
    L += ["key F 0.06\n", "\n".join(stepseq(90, 6, PASSIN, "flare_")) + "\n", "key C 0.06\n", "\n".join(stepseq(90, 6, PASSIN, "chaff_")) + "\n", "key J 0.06\n", "\n".join(stepseq(60, 6, PASSIN, "ecm_")) + "\n", tail("sound-gun-launch")]
    write("sound-gun-launch", "".join(L))

    # 10 the demonstration flight up to its first missile launch: the lock cue, the launch, the engine pitch (the demo fires an AIM-120 near blank 8,000)
    L = [head("demo.vasnap", "sound-cue"), "\n".join(PASSIN) + "\n", "stepuntil F:54E5C 4 eq 0xC5473F 9000\n", "\n".join(PASSIN) + "\n",
         "\n".join(stepseq(300, 6, PASSIN, "x")) + "\n", tail("sound-cue")]
    write("sound-cue", "".join(L))

    # 11 views: external view (KP-Enter), the map (M), the pause (P) and their returns while the engine runs
    L = [head("airborne.vasnap", "sound-views"), "\n".join(PASSIN) + "\n"]
    for i, (k, n) in enumerate((("KPENTER", 90), ("KPENTER", 90), ("M", 90), ("M", 90), ("P", 90), ("P", 90), ("KP4", 60), ("KP2", 60))):
        L.append("key %s 0.06\n" % k)
        L.append("\n".join(stepseq(n, 6, PASSIN, "%s%d_" % (k, i))) + "\n")
    L.append(tail("sound-views"))
    write("sound-views", "".join(L))


if __name__ == "__main__":
    main()
