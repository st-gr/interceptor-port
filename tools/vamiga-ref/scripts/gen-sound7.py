#!/usr/bin/env python3
"""Generate the sound capture scripts of milestone 7 (note 10, the open questions of the event table): sound7-*.txt next to this file.

    python3 tools/vamiga-ref/scripts/gen-sound7.py [name ...]

Every script restores a snapshot, freezes the machine, switches `audtrace` on (one line per video frame, or every register write for the click captures), presses keys or
pokes run-time state and runs the machine with `step` (one video frame each), so the logs do not depend on the wall clock.  The staged scripts poke only run-time
variables (a sound request's bytes, the cue long, the countdown byte); the staged hostile of the bang scripts is the one of followup-combat-kills.txt (its record fields,
moved by the driver's `copy`).  Run each one alone under the emulator lock, from the repository root:

    flock /tmp/ref.lock timeout 900 build/vamiga-ref/ref --rom disks/kick12.rom --adf extracted/interceptor-autoboot.adf \\
        --script tools/vamiga-ref/scripts/sound7-gun.txt --log extracted/captures/logs/sound7-gun.txt

The logs are read by tools/vamiga-ref/sound7_trace.py (the voices' runs) and logparse.py (the peeks); the port's side is tools/vamiga-ref/sound7_port.c.
"""
import os
import sys
HERE = os.path.dirname(os.path.abspath(__file__))
SEG = "seglist extracted/interceptor.bin extracted/interceptor.map.json"

# the globals V:4A83C..4A99B in one group (gates, the view bytes, the notice, the hold, the countdown bytes, the cue cool-down, the pass counter 4A992, the camera 4A994/4A996), the
# cue long, the offset word the walkers store (V:4AA6E), the camera distance, the system clock longs
G = ["peek F:4A83C 352 g", "peek F:4AA6C 4 w6e", "peek F:4AC0C 4 cues", "peek F:4ABFA 2 dist", "peek F:4ABAA 8 clk"]
SND = ["peek F:54FBE 4 m", "peek F:4A720 4 t", "peek F:4A88F 1 f", "peek F:4A82C 2 bl"]


def head(snap, name, mode="frame", more=()):
    s = ["# %s" % name, "# generated by gen-sound7.py (note 10, milestone 7); see that file for how to run it.", "restore extracted/captures/%s" % snap, SEG, "freeze"]
    s += list(more)
    s.append("audtrace on%s" % {"frame": " frame", "watch": "", "nodmacon": " nodmacon"}[mode])
    return s


def tail():
    return ["audtrace off"]


def run(n, per, peeks, tag):
    out = []
    for i in range(0, n, per):
        out.append("step %d" % min(per, n - i))
        out += [p + "_%s%d" % (tag, i) for p in peeks]
    return out


def lab(peeks, tag):
    return [p + "_" + tag for p in peeks]


def write(name, lines):
    with open(os.path.join(HERE, name + ".txt"), "w") as f:
        f.write("\n".join(lines) + "\n")


def staged_mig():
    """the staging lines of followup-combat-kills.txt up to the weapon selection: a placed MiG 12 passes ahead of the player, the gun selected"""
    src = open(os.path.join(HERE, "followup-combat-kills.txt")).read().split("\n")
    i = src.index("freeze")
    j = next(k for k, l in enumerate(src) if l.startswith("peek F:1D024"))
    return src[i + 1:j]


def main(only):
    def want(n):
        return not only or n in only

    # 1 two gun bursts in the cockpit view more than 28 blanks apart (the second burst's pulses at 280), then two in the outside view (volume 30)
    if want("gun"):
        L = head("airborne.vasnap", "sound7-gun") + G
        L += run(24, 12, G[:1], "w") + ["peek F:4B29B 8 sel", "poke F:4B29F 1 0x1D", "poke F:4B29B 1 0x44", "peek F:4B29B 8 sel2"] + run(24, 12, G[:1], "w2")   # the gun selected as the staged scripts do (+0x63, rounds +0x5F)
        L += ["keydown SPACE"] + run(36, 12, G[:1], "b1h") + ["keyup SPACE"] + run(120, 12, G[:1], "b1a")
        L += ["keydown SPACE"] + run(36, 12, G[:1], "b2h") + ["keyup SPACE"] + run(120, 12, G[:1], "b2a")
        L += ["key KPENTER 0.06"] + run(60, 12, G[:1], "x")
        L += ["keydown SPACE"] + run(36, 12, G[:1], "b3h") + ["keyup SPACE"] + run(120, 12, G[:1], "b3a")
        L += ["keydown SPACE"] + run(36, 12, G[:1], "b4h") + ["keyup SPACE"] + run(120, 12, G[:1], "b4a")
        write("sound7-gun", L + tail())

    # 2 the explosion bang: the staged MiG killed by the gun (the dying record drawn with its counter at 14), in the cockpit view and in the outside view
    for ext in (0, 1):
        n = "bang-ext" if ext else "bang"
        if not want(n):
            continue
        P = ["peek F:4A870 1 cd", "peek F:4A921 2 ad", "peek F:4A963 1 kills", "peek F:4C23C 4 w0", "peek F:4A992 2 pass", "peek F:4A83D 1 view"]
        L = head("airborne.vasnap", "sound7-" + n) + staged_mig()
        L += ["poke F:4AA78 2 0x1000"]
        if ext:
            L += ["key KPENTER 0.06", "step 30"]
        L += P
        for k in range(190):
            if k < 4:
                L.append("poke F:4AA78 2 0x1000")
            if k == 3:
                L.append("keydown SPACE")
            L.append("step 6")
            L += lab(P, "s%d" % k)
        L += ["keyup SPACE"] + tail()
        write("sound7-" + n, L)

    # 3 a pending bang overwritten by a later writer, after a control bang (the bytes the entity drawer and the seat write: V:4A922, V:4A921 and the countdown V:4A870)
    if want("bang-overwrite"):
        P = ["peek F:4A870 1 cd", "peek F:4A921 2 ad", "peek F:4A992 2 pass"]
        L = head("airborne.vasnap", "sound7-bang-overwrite") + G + P
        L += ["# control: arguments (0x20, 0x50) with the countdown 2 and no later writer", "poke F:4A922 1 0x20", "poke F:4A921 1 0x50", "poke F:4A870 1 2"] + P
        L += ["stepuntil F:4A870 1 eq 0 200"] + P + run(150, 15, P, "c")
        L += ["# overwritten: (0x20, 0x50) with the countdown 4; one pass later (the countdown reads 3) a later writer stores (0x30, 0x60) and the countdown 4 again",
              "poke F:4A922 1 0x20", "poke F:4A921 1 0x50", "poke F:4A870 1 4", "stepuntil F:4A870 1 eq 3 200"] + P
        L += ["poke F:4A922 1 0x30", "poke F:4A921 1 0x60", "poke F:4A870 1 4", "stepuntil F:4A870 1 eq 3 200", "stepuntil F:4A870 1 eq 0 200"] + P + run(150, 15, P, "o")
        write("sound7-bang-overwrite", L + tail())

    # 4 the cue bits 0x10, 0x800, 0x40 and 0x01, one at a time through the cue long, then 0x10 while the cool-down of 0x01 runs
    if want("cues"):
        P = ["peek F:4AC0C 4 cues", "peek F:4A942 1 cool", "peek F:4A992 2 pass", "peek F:4ABAA 4 sec"]
        L = head("airborne.vasnap", "sound7-cues") + G
        for bit, wait in ((0x10, 70), (0x800, 50), (0x40, 200), (0x01, 160)):
            L += ["# cue 0x%X" % bit, "poke F:4AC0C 4 0x%X" % bit] + P + ["stepuntil F:4AC0C 4 eq 0 200"] + P + run(wait, 10, P, "w%X_" % bit)
        L += ["# 0x10 right after 0x01: held by the cool-down", "poke F:4AC0C 4 0x10"] + P + run(300, 10, P, "h")
        write("sound7-cues", L + tail())

    # 4b the cool-down of the cue 0x01 (3 ticks of the clock): 0x10 poked 20 frames after it, held until the cool-down has run out; twice, 100 frames apart in phase
    if want("cues-hold"):
        P = ["peek F:4AC0C 4 cues", "peek F:4A942 1 cool", "peek F:4A992 2 pass", "peek F:4ABAA 8 clk"]
        L = head("airborne.vasnap", "sound7-cues-hold") + G
        for rep in range(2):
            L += ["poke F:4AC0C 4 0x01", "stepuntil F:4AC0C 4 eq 0 200", "step 20", "poke F:4AC0C 4 0x10"] + P + ["stepuntil F:4AC0C 4 eq 0 400"] + P + run(200, 10, P, "r%d_" % rep)
            L += run(7 * rep + 13, 1, [], "x")
        write("sound7-cues-hold", L + tail())

    # 5 the pause in the air: the key, the clicks of the typed pause text, the unpause; every register write traced (the PC after each write is in the log)
    if want("pause"):
        P = ["peek F:4A82C 2 bl", "peek F:4A866 1 pause", "peek F:4A942 1 cool", "peek F:4A88F 1 f", "peek F:4A992 2 pass"]
        L = head("airborne.vasnap", "sound7-pause", mode="nodmacon") + G + P + run(12, 12, P, "a")
        L += ["key P 0.06"] + run(80, 8, P, "p") + ["key P 0.06"] + run(60, 6, P, "u")
        write("sound7-pause", L + tail())

    # 5b who requests the pause clicks: the two call sites of the click routine (the bsr at 0x376F8 of the text engine's character routine, the one at 0x37B18 at the end of an instant line) and
    # the routine itself, each stopped at in turn after the key (no audio trace: a per-write trace slows the machine and misses breakpoints); the frame census with the same key follows below
    for name, addr in (("376F8", "376F8"), ("37B18", "37B18"), ("37C2E", "37C2E")):
        if not want("pause-at-" + name):
            continue
        P = ["peek F:4A992 2 pass", "peek F:4A82C 2 bl", "peek F:4A866 1 pause", "peek F:4A942 1 cool"]
        L = ["# sound7-pause-at-%s" % name, "# generated by gen-sound7.py (note 10, milestone 7); see that file for how to run it.", "restore extracted/captures/airborne.vasnap", SEG, "freeze", "step 12"] + P
        L += ["key P 0.06"]
        for i in range(24):
            L += ["runto F:%s 2 soft" % addr] + lab(P, "h%d" % i)
        write("sound7-pause-at-" + name, L)
    # 5c the same for the typed lines before the menu build of SHIFT-ESC: the click call sites stopped at in turn after the key (no audio trace)
    for name, addr in (("376F8", "376F8"), ("37B18", "37B18")):
        if not want("restart-at-" + name):
            continue
        P = ["peek F:4A992 2 pass", "peek F:4A82C 2 bl", "peek F:1A6BC 4 st", "peek F:4A88F 1 f"]
        L = ["# sound7-restart-at-%s" % name, "# generated by gen-sound7.py (note 10, milestone 7); see that file for how to run it.", "restore extracted/captures/airborne.vasnap", SEG, "freeze", "step 12"] + P
        L += ["keydown LSHIFT", "key ESC 0.12", "keyup LSHIFT"]
        for i in range(30):
            L += ["runto F:%s 1 soft" % addr] + lab(P, "h%d" % i)
        write("sound7-restart-at-" + name, L)
    if want("pause-frames"):
        P = ["peek F:4A992 2 pass", "peek F:4A866 1 pause", "peek F:4A942 1 cool"]
        L = head("airborne.vasnap", "sound7-pause-frames") + P + run(12, 12, P, "a") + ["key P 0.06"]
        for i in range(120):
            L += ["step 1"] + lab(P, "k%d" % i)
        L += ["key P 0.06"]
        for i in range(60):
            L += ["step 1"] + lab(P, "u%d" % i)
        write("sound7-pause-frames", L + tail())

    # 6 the fixed camera (SHIFT and KP-ENTER clears V:4A86D), the gear key in it, and the camera test of the wrappers
    if want("fixedcam"):
        L = head("airborne.vasnap", "sound7-fixedcam") + G
        L += ["keydown LSHIFT", "key KPENTER 0.12", "keyup LSHIFT"] + run(60, 20, G, "fx")
        L += ["poke F:4A93D 1 0x83"] + run(120, 6, G[:1] + G[1:2], "g1_")
        L += ["runto F:1A1E6 2 soft", "peek F:4AA6C 4 w6e_at1A1E6", "peek F:4A994 4 cam_at1A1E6"]
        L += ["key KPENTER 0.06"] + run(40, 20, G, "ring") + ["poke F:4A93D 1 0x83"] + run(150, 6, G[:1] + G[1:2], "g2_")
        write("sound7-fixedcam", L + tail())

    # 7 the ejection seat: SHIFT-E, then the gear countdown poked while the camera is on the seat; the wrapper's entry stopped at
    if want("seat"):
        L = head("airborne.vasnap", "sound7-seat") + G
        L += ["keydown LSHIFT", "key E 0.12", "keyup LSHIFT"] + run(240, 12, G, "e")
        L += ["poke F:4A93D 1 0x83"] + run(60, 6, G[:1] + G[1:2], "g_")
        L += ["runto F:1A1E6 2 soft", "peek F:4AA6C 4 w6e_at1A1E6", "peek F:4A994 4 cam_at1A1E6"]
        L += run(120, 12, G, "after")
        write("sound7-seat", L + tail())

    # 8 the pod release: SHIFT-F in mode 6 (the mission-F4 flight snapshot)
    if want("pod"):
        P = ["peek F:4A95E 1 mode", "peek F:4A97A 2 latch", "peek F:4B2B8 1 nib", "peek F:4B43D 1 b1", "peek F:4B63D 1 b2", "peek F:4B83D 1 b3", "peek F:4AC12 2 en"]
        L = head("mission-m6-flight.vasnap", "sound7-pod") + P + ["keydown LSHIFT", "key F 0.12", "keyup LSHIFT"] + run(120, 6, P, "p")
        write("sound7-pod", L + tail())

    # 9 the seconds tick: V:4ABAA and the counters it drives over 120 s (6,000 frames) of flight, with a gear countdown, a head key and a cue 0x01 in it
    if want("tick"):
        P = ["peek F:4A93C 16 cnt", "peek F:4ABAA 8 clk", "peek F:4A992 2 pass"]
        L = ["# sound7-tick", "# generated by gen-sound7.py (note 10, milestone 7); see that file for how to run it.", "restore extracted/captures/airborne.vasnap", SEG, "freeze"] + P
        for k in range(1500):
            if k == 60:
                L.append("poke F:4A93D 1 0x83")
            if k == 600:
                L.append("key KP6 0.06")
            if k == 1000:
                L.append("poke F:4AC0C 4 0x01")
            if k == 1250:
                L.append("poke F:4A93D 1 0x83")
            L.append("step 4")
            L += lab(P, "t%d" % k)
        write("sound7-tick", L)

    # 10 the approach: the sound routine's entry stopped at in every pass of a mission start (mode 3), with its gates
    if want("approach"):
        P = ["peek F:4A966 1 gate", "peek F:4A84D 1 game", "peek F:4A82C 2 bl", "peek F:4A83D 2 view", "peek F:4ABFA 2 dist", "peek F:4A86E 2 stage", "peek F:4A968 1 notice", "peek F:4A992 2 pass"]
        L = ["# sound7-approach", "# generated by gen-sound7.py (note 10, milestone 7); see that file for how to run it. Needs the git-ignored disks/countercodes.txt.",
             "restore extracted/captures/mb/m3-prompt.vasnap", SEG, "code @disks/countercodes.txt 429C", "wait 16", "freeze", "audtrace on frame", "key 1 0.12"]
        for i in range(210):
            L += ["runto F:14AA0 3 soft"] + lab(P, "r%d" % i)
        L += ["step 100"] + P
        write("sound7-approach", L + tail())

    # 11 the post-flight menu: SHIFT-ESC from the air, the menu build and the music restart; every register write traced (clicks and wrapper calls in one step)
    if want("restart"):
        P = SND + ["peek F:1A6BC 4 st"]
        L = head("airborne.vasnap", "sound7-restart", mode="nodmacon") + P + ["keydown LSHIFT", "key ESC 0.12", "keyup LSHIFT"]
        L += run(1800, 30, P, "r")
        write("sound7-restart", L + tail())

    # 11b the swallow (note 10 5.1 item 7): the gear byte poked (the key's store) d frames before the pass that sees a new seconds long; the sound routine runs before the tick if the gear
    # sound starts in that pass. V:4ABAA is 0x5BC1585D at the restore of the snapshot (sound7-tick); each trial syncs on the pass that stores the next seconds long four seconds later.
    if want("swallow"):
        S0 = 0x5BC1585D
        P = ["peek F:4A93D 1 gear", "peek F:4A992 2 pass", "peek F:4ABAA 8 clk"]
        L = head("airborne.vasnap", "sound7-swallow") + P
        for i, d in enumerate((16, 14, 12, 10, 8, 6, 4, 2, 0), 1):
            L += ["stepuntil F:4ABAA 4 gt 0x%X 400" % (S0 + 4 * i - 1)] + lab(P, "sync%d" % i)
            L += ["step %d" % (50 - d), "poke F:4A93D 1 0x83"] + lab(P, "poke%d" % i) + run(48, 4, P, "t%d_" % i)
        write("sound7-swallow", L + tail())

    # 12 the touchdown of the camera's aircraft on a surface (the contact sound 0x1A18C: volume 0x1E for a descent per step up to 0x180, 0x28 above it, a crash from 0x240): (a) the airborne
    # snapshot with the player's altitude long (V:4B254) poked below the surface floor of the step, the aircraft climbing (descent negative: 0x1E); (b) the dive snapshot with the speed words
    # (b) the dive snapshot with the speed words (V:4B2A8, V:4B2AA) poked to 800 or 900 (at most 0x3C0 = 960: no crash from the collision step), the altitude to 5500 and the vertical velocity long (V:4B27E, minus four times the descent per step) to -1920 or -2100: the descent per step the step compares is about 2.7 times V:4AB06 here (the record's smoothed velocity), so a contact two or three passes later should fall between 0x180 and 0x240 (0x28)
    if want("landing"):
        P = ["peek F:4B23C 168 r0", "peek F:4AB04 6 vel", "peek F:4A850 1 end", "peek F:4A878 1 jolt", "peek F:4A83D 1 view"]
        L = ["# sound7-landing", "# generated by gen-sound7.py (note 10, milestone 7); see that file for how to run it."]
        for tag, snap, pokes in (("a", "airborne", ["poke F:4B254 4 -9000"]), ("b", "dive-precrash", ["poke F:4B2A8 2 800", "poke F:4B2AA 2 800", "poke F:4B254 4 5500", "poke F:4B27E 4 -1920"]), ("d", "dive-precrash", ["poke F:4B2A8 2 900", "poke F:4B2AA 2 900", "poke F:4B254 4 5500", "poke F:4B27E 4 -2100"])):
            L += ["restore extracted/captures/%s.vasnap" % snap, SEG, "freeze", "audtrace on frame", "step 12"] + pokes
            L += P + run(2, 1, P, tag + "s") + run(150, 3, P, tag + "t") + ["audtrace off"]
        write("sound7-landing", L)


if __name__ == "__main__":
    main(set(sys.argv[1:]))
