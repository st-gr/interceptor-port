import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, HERE)
import sound7_trace as T       # noqa: E402
import logparse                # noqa: E402

LOGS = os.path.join(ROOT, "extracted", "captures", "logs")
PORT = os.path.join(ROOT, "build", "sound7_port")
GOLDEN = os.path.join(ROOT, "build", "tests", "run_golden")


def log(item):
    p = os.path.join(LOGS, "sound7-%s.txt" % item)
    return p if os.path.exists(p) else None


def port_run(item, voice=None):
    """the port's register writes for tools/vamiga-ref/scripts/sound7-<item>.port, as a file under /tmp"""
    out = "/tmp/sound7-%s.port.out" % item
    with open(out, "w") as f:
        subprocess.run([PORT, os.path.join(ROOT, "assets"), os.path.join(HERE, "scripts", "sound7-%s.port" % item)], stdout=f, check=True, cwd=ROOT)
    return out


def eq(a, b, slip=0):
    """equal blanks of two sequences over the shorter one, the capture's leading sample (the register state before the first write of a start) dropped by the caller"""
    n = min(len(a), len(b))
    best = 0
    for s in range(-slip, slip + 1):
        e = sum(1 for i in range(n) if 0 <= i + s < len(a) and a[i + s] == b[i])
        best = max(best, e)
    return best, n


def vols(seq):
    return [v for _, v in seq]


def bang_stretches(path):
    """the stretches of voice 2 with DMA on and a period above 5,000 (the noise: a bang), as lists of volumes"""
    out, cur, last = [], None, None
    for f, dma, per, vol in T.emu_series(path, 2):
        if dma and per > 5000:
            if cur is None or f != last + 1:
                cur = []
                out.append(cur)
            cur.append((per, vol))
            last = f
        else:
            cur = None
    return out


def item_bang(name):
    cap = bang_stretches(log(name))
    port = T.runs(T.port_series(port_run("bang"), 2))
    ext = name == "bang-ext"
    p = [r for r in port if r[1][0][0] > 5000][1 if ext else 0][1]
    # a second bang may cut the first (the outside capture: two bangs 32 blanks apart); a stretch is split where the period changes, and the longest piece (the bang that ran to its end) is compared
    pieces = []
    for st in cap:
        cur = [st[0]]
        for q in st[1:]:
            if q[0] == cur[-1][0]:
                cur.append(q)
            else:
                pieces.append(cur)
                cur = [q]
        pieces.append(cur)
    best = max(pieces, key=len)
    a = [v for _, v in best]
    e, n = eq(a[1:], vols(p))
    print("%s: %d bangs in the capture (pieces of %s blanks), the longest (period %d) starts at volume %d, the port's at %d; its volume curve: %d of %d blanks equal" % (
        name, len(pieces), [len(x) for x in pieces], best[0][0], a[1], vols(p)[0], e, n))


def item_bang_overwrite():
    cap = T.runs(T.emu_series(log("bang-overwrite"), 2))
    port = T.runs(T.port_series(port_run("bang-overwrite"), 2))
    for i, ((cf, cs), (pf, ps)) in enumerate(zip(cap, port)):
        e, n = eq(vols(cs)[1:], vols(ps))
        print("bang-overwrite run %d: capture %d blanks (first volume %d), port %d blanks (first volume %d), %d of %d equal" % (i, len(cs), vols(cs)[1], len(ps), vols(ps)[0], e, n))


def item_cues():
    cap = T.runs(T.emu_series(log("cues"), 3))
    port = T.runs(T.port_series(port_run("cues"), 3))
    tot = ok = 0
    for i, ((cf, cs), (pf, ps)) in enumerate(zip(cap[:5], port[:5])):
        e, n = eq(cs[1:], ps)
        tot += n
        ok += e
        print("cues tone %d: capture %d blanks, port %d, %d of %d equal" % (i, len(cs), len(ps), e, n))
    print("cues: %d of %d blanks equal" % (ok, tot))


