def item_gun():
    cap = T.runs(T.emu_series(log("gun"), 2))
    port = T.runs(T.port_series(port_run("gun"), 2))
    pairs = [(cap[2], port[0]), (cap[3], port[1]), (cap[4], port[2]), (cap[7], port[3])]
    tot = ok = 0
    for (cf, cs), (pf, ps) in pairs:
        a, b = cs[-29:], ps[-29:]
        e, n = eq(a, b, slip=1)
        tot += n
        ok += e
    pers = [sorted(set(p for p, _ in r[1])) for r in cap]
    print("gun: %d runs in the capture (periods per run %s); the last shot of each burst: %d of %d blanks equal (period and volume), the rest within one unit at the tail" % (len(cap), pers, ok, tot))


def item_pod():
    cap = T.runs(T.emu_series(log("pod"), 2))[0][1][1:]
    d = "/tmp/sound7-pod.golden.out"
    with open(d, "w") as f:
        subprocess.run([GOLDEN, "--audio-dump", os.path.join(ROOT, "assets"), os.path.join(ROOT, "tests", "golden", "mission-f4.txt")], stdout=f, check=True, cwd=ROOT)
    port = [r for r in T.runs(T.port_series(d, 2)) if r[1][0] == (cap[0][0], 28)][0][1]
    e, n = eq(cap, port)
    print("pod: capture %d blanks (28 falling, period %d), port mission-F4 run %d blanks, %d of %d equal" % (len(cap), cap[0][0], len(port), e, n))


def item_pause():
    path = log("pause")
    t = open(path).read().split("\n")
    idx = [i for i, l in enumerate(t) if l.startswith("seg 0 flat")]
    t = t[idx[-1]:]
    starts = []
    stop = None
    for l in t:
        m = re.match(r"aud frame (\d+) line (\d+) hpos \d+ pc (\w+) dmacon \w+ changed (.*?) \|", l)
        if not m:
            continue
        f = int(m.group(1))   # the library blank of a write: the video frame (milestone 7: the raster fraction put the first start in the next blank and gave +13.1, 15.5, 17.4, ...)
        if stop is None and "VOL0=0" in m.group(4):
            stop = f
        if m.group(3) == "C4CDF4" and "DMACON" in m.group(4) and "PER3=300" in m.group(4):
            starts.append(f)
    off = [x - stop for x in starts]
    pa = port_run("pause")
    ps = [(25 * (int(l.split()[0]) - 1) // 4 + int(l.split()[4])) for l in open(pa) if l.split()[1] == "2" and l.split()[2] == "3" and int(l.split()[0]) < 30 and int(l.split()[0]) >= 20]
    key = 25 * 19 // 4
    print("pause: the capture's click starts after the stop of voices 0/1 (blanks): %s; the port's click starts after the key's blank: %s" % (off, [x - key for x in ps]))


def gear_spans(path):
    """voice 2 stretches that start at the gear object's period 358 or 700, as (first frame, frame span, last volume)"""
    ser = T.emu_series(path, 2)
    out, cur = [], None
    for f, dma, per, vol in ser:
        if dma and per in (358, 700, 693, 686, 679, 672, 665, 658, 651, 644, 637, 630, 623, 616, 609, 602, 595) and vol in (10, 5):
            if cur is None:
                cur = [f, f, vol]
                out.append(cur)
            cur[1] = f
        elif cur is not None and not dma:
            cur = None
    return [(a, b - a + 1, v) for a, b, v in out]


