def item_tick():
    path = log("tick")
    t = open(path).read().split("\n")
    idx = [i for i, l in enumerate(t) if l.startswith("seg 0 flat")]
    open("/tmp/sound7-tick.last", "w").write("\n".join(t[idx[-1]:] if idx else t))
    L = logparse.load("/tmp/sound7-tick.last")
    prev = None
    secs = []
    ev = []
    prevc = None
    k = 0
    while ("clk_t%d" % k) in L:
        sec = L["clk_t%d" % k].u32(0)
        cnt = L["cnt_t%d" % k].data
        cur = (cnt[1], cnt[6], cnt[0x0D])       # V:4A93D the gear byte, V:4A942 the cool-down, V:4A949 the head hold
        f = 4 * (k + 1)
        if prev is not None and sec != prev:
            secs.append(f)
        if prevc is not None:
            g0, c0, h0 = prevc
            g1, c1, h1 = cur
            if (g0 >= 2 and g1 == g0 - 1) or (g0 == 0 and g1 == 2):
                ev.append((f, "gear"))
            if (1 <= c0 <= 3 and c1 == c0 - 1) or (c0 == 0 and c1 == 0xFF):
                ev.append((f, "cool"))
            if (2 <= h0 <= 5 and h1 == h0 - 1) or (h0 == 1 and h1 == 0xFF):
                ev.append((f, "hold"))
        prev, prevc = sec, cur
        k += 1
    on = sum(1 for f, n in ev if f in secs)
    print("tick: %d samples, V:4ABAA changed %d times (%.2f frames a second); %d decrements of the gear byte, the cool-down and the head hold, %d in a sample in which the seconds long changed" % (k, len(secs), (secs[-1] - secs[0]) / (len(secs) - 1.0), len(ev), on))


def item_restart():
    path = log("restart")
    ev = []
    for l in open(path):
        m = re.match(r"aud frame (\d+) line (\d+) hpos \d+ pc \w+ dmacon \w+ changed (.*?) \|", l)
        if not m:
            continue
        t = int(m.group(1)) + int(m.group(2)) / 313.0
        for tok in m.group(3).split():
            if tok.startswith("LC0="):
                ev.append(("lc", t, int(tok[4:], 16)))
            if tok.startswith("LEN0="):
                ev.append(("len", t, int(tok[5:], 16)))
    pairs = []
    cl = None
    for e in ev:
        if e[0] == "lc":
            cl = e
        if e[0] == "len" and cl is not None and abs(e[1] - cl[1]) < 0.02:
            pairs.append((cl[1], cl[2], e[2]))
    start = next(p for p in pairs if p[2] == 0x3FE)
    blocks = [start, pairs[pairs.index(start) + 1]]
    bt = [start[0], start[0] + start[2] * 2 * 358 / 71051.0]
    k = 1
    while k < 40:
        cand = [p for p in pairs if abs(p[0] - bt[k]) < 0.15 and p is not blocks[k]]
        blocks.append(cand[-1] if cand else blocks[k])
        bt.append(bt[k] + blocks[k][2] * 2 * 358 / 71051.0)
        k += 1
    names = {0x3FE: "texti0a", 0x3EE: "texti0b", 0x4001: "texti1", 0x4009: "texti2", 0x4049: "texti3", 0x3FE0: "?", 0x3FD0: "texti4"}
    runs = []
    for b in blocks[:-1]:
        n = names.get(b[2], "len%d" % b[2])
        if runs and runs[-1][0] == n:
            runs[-1][1] += 1
        else:
            runs.append([n, 1])
    print("restart: voice 0 after the menu build (blocks): %s" % " ".join("%s x%d" % tuple(r) for r in runs[:8]))
    restart_clicks(path)


def restart_clicks(path):
    """the click starts of voice 3 after the stop of the voices (SHIFT-ESC from the air): the capture's against the port's, in blanks after the stop (milestone 7: no click comes before the stop; the music restarts at k = 11)"""
    t = open(path).read().split("\n")
    idx = [i for i, l in enumerate(t) if l.startswith("seg 0 flat")]
    t = t[idx[-1]:]
    starts, stop, before = [], None, 0
    for l in t:
        m = re.match(r"aud frame (\d+) line (\d+) hpos \d+ pc (\w+) dmacon \w+ changed (.*?) \|", l)
        if not m:
            continue
        f = int(m.group(1))   # the library blank of a write: the video frame (the vertical-blank run precedes the main loop's calls in the frame), not the raster position
        if stop is None and "VOL0=0" in m.group(4):
            stop = f
        if "DMACON" in m.group(4) and "PER3=300" in m.group(4):
            if stop is None:
                before += 1
            else:
                starts.append(f - stop)
    pa = port_run("restart")
    rows = [l.split() for l in open(pa)]
    def bl(r):
        return 25 * (int(r[0]) - 1) // 4 + int(r[4])
    pstop = next(bl(r) for r in rows if int(r[0]) >= 20 and r[1] == "2" and r[2] == "0")
    pst = sorted(set(bl(r) - pstop for r in rows if int(r[0]) >= 20 and r[1] == "2" and r[2] == "3"))
    ex = sum(1 for x in pst if x in starts)
    print("restart: click starts of voice 3 before the stop: capture %d; after it (library blanks after the stop): capture %d, port %d, equal to the blank %d; first: capture %d, port %d" % (before, len(starts), len(pst), ex, starts[0], pst[0]))


def item_approach():
    txt = open(log("approach")).read().split("\n")
    rows = []
    cur = None
    for l in txt:
        if l.startswith("# runto"):
            cur = {"hit": "reached" in l}
            rows.append(cur)
            continue
        p = l.split()
        if cur is not None and len(p) >= 3 and p[1].startswith("F:") and re.search(r"_r\d+$", p[0]):
            cur[re.sub(r"_r\d+$", "", p[0])] = p[2]       # the peeks of the closing step (no suffix) are not an entry
    gate6 = sum(1 for r in rows if r.get("gate") == "06")
    open_ = [i for i, r in enumerate(rows) if r.get("gate") == "00" and r.get("game") == "01"]
    print("approach: %d entries of the sound routine reached; gate V:4A966 = 6 in %d of them (V:4ABFA read by none); ungated passes with V:4A84D open: %d (the first at entry %d); V:4A84D clear afterwards in %d entries" % (
        sum(1 for r in rows if r["hit"]), gate6, len(open_), open_[0] if open_ else -1, sum(1 for r in rows if r.get("game") == "00")))


def item_landing():
    path = log("landing")
    fr = T.load_aud(path)
    prev = None
    out = []
    for f in sorted(fr):
        d, v = fr[f]
        st = (bool(d & 4), v[2][2], v[2][3])
        if st != prev and st[0] and v[2][2] == 310:
            out.append((f, v[2][3]))
        prev = st
    print("landing: voice 2 starts at period 310 (frame, volume): %s" % out)


ITEMS = {"gun": item_gun, "bang": lambda: item_bang("bang"), "bang-ext": lambda: item_bang("bang-ext"), "bang-overwrite": item_bang_overwrite, "cues": item_cues, "cues-hold": item_cues_hold,
         "pod": item_pod, "pause": item_pause, "fixedcam": item_fixedcam, "seat": item_seat, "restart": item_restart, "tick": item_tick, "approach": item_approach, "landing": item_landing}

if __name__ == "__main__":
    want = sys.argv[1:] or list(ITEMS)
    for it in want:
        if log(it) is None:
            print("%s: skipped (no log)" % it)
            continue
        try:
            ITEMS[it]()
        except Exception as e:      # a missing port binary or a truncated log: say so, go on
            print("%s: not checked (%s)" % (it, e))
