#!/usr/bin/env python3
"""The milestone-7 sound captures of note 10 against the port: the counts the note quotes.

    cc -std=c99 -O1 -Isrc/core tools/vamiga-ref/sound7_port.c build/libcore.a -o build/sound7_port -lm     # once (make core first)
    python3 tools/vamiga-ref/sound7_check.py [item ...]          items: gun bang bang-ext bang-overwrite cues cues-hold pod pause fixedcam seat restart tick approach landing

Each item reads the git-ignored log extracted/captures/logs/sound7-<item>.txt (the scripts are tools/vamiga-ref/scripts/sound7-<item>.txt, generated by gen-sound7.py), runs the
port on the same events (tools/vamiga-ref/scripts/sound7-<item>.port through build/sound7_port, or build/tests/run_golden for the mission run of the pod) and prints, per item, what was
compared and how many blanks (or events) agree.  An item whose log is absent is skipped; the exit status is 0 (a difference is a finding for the note's deviation table, not a failure).
No sample byte and no game text is read or written: only register values, frame numbers and the game's run-time variables from the peeks.
"""
import os
